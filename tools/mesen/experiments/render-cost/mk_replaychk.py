#!/usr/bin/env python3
"""mk_replay.py <harness run.log> <out.lua> [end_frame]

Builds a standalone Lua script (no lib, no pixel reads) that replays a harness
run's recorded input: the [ot6pad] <frame> <buttons> stream, and the savestate
loads named by "[ot6note] <frame> loading savestate <name>" lines (the fixture
bytes are inlined from build/states/<name>).  Frames count startFrame events
from script load, as lib/ot6.lua's M.frame does; a pad stamped f is applied
from the inputPolled of frame f on, a load stamped f is requested at startFrame
f and performed in the next exec callback (Mesen allows loads only there).

It is not guaranteed to reproduce the harness run (the harness also idles,
reloads its own boot snapshots, ...); what matters here is that it feeds every
emulator variant the same inputs with no pixel reads.  At end_frame (default:
the run's verdict frame) it prints [rcdump]/[rcstate] like the instrumented lib
and stops; it also prints "[rcreplay] done <frames>".
"""
import re, sys, os

log, out = sys.argv[1], sys.argv[2]
txt = open(log, errors="replace").read()
pads = [(int(f), b) for f, b in re.findall(r"^\[ot6pad\] (\d+) (\S+)", txt, re.M)]
loads = [(int(f), n) for f, n in re.findall(r"^\[ot6note\] (\d+) loading savestate (\S+)", txt, re.M)]
if len(sys.argv) > 3:
    end = int(sys.argv[3])
else:
    end = int(re.findall(r"^\[ot6\] (?:PASS \(frame |FAIL: .*?f)(\d+)", txt, re.M)[-1])
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
L = []
L.append("-- generated by build/rc/mk_replay.py from %s\n" % log)
L.append("local PADS = {\n")
for f, b in pads:
    L.append('  {%d, "%s"},\n' % (f, b))
L.append("}\nlocal LOADS = {\n")
for f, n in loads:
    p = os.path.join(root, "build", "states", n)
    s = open(p).read().strip()
    assert s.startswith('return "') and s.endswith('"'), p
    L.append('  {%d, "%s"},\n' % (f, s[8:-1]))
L.append("}\nlocal END = %d\n" % end)
L.append(r'''
local B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local B64I = {}
for i = 1, 64 do B64I[B64:sub(i, i)] = i - 1 end
local function b64decode(s)
  local out, n = {}, 0
  local bits, nb = 0, 0
  for i = 1, #s do
    local v = B64I[s:sub(i, i)]
    if v then
      bits = (bits << 6) | v; nb = nb + 6
      if nb >= 8 then
        nb = nb - 8
        n = n + 1; out[n] = string.char((bits >> nb) & 0xFF)
      end
    end
  end
  return table.concat(out)
end

local ALL = { "a", "b", "x", "y", "l", "r", "select", "start", "up", "down", "left", "right" }
local pad = {}
for _, k in ipairs(ALL) do pad[k] = false end
local function setPad(spec)
  for _, k in ipairs(ALL) do pad[k] = false end
  if spec ~= "--" then for k in spec:gmatch("[^+]+") do pad[k] = true end end
end

local frame, pi, li = 0, 1, 1
local pendingLoad = nil
local execRef = nil
emu.addEventCallback(function() emu.setInput(pad, 0) end, emu.eventType.inputPolled)

local function rcDump()
  local mt = emu.memType
  for _, r in ipairs({ {"wram", mt.snesWorkRam}, {"aram", mt.spcRam},
                       {"vram", mt.snesVideoRam}, {"oam", mt.snesSpriteRam},
                       {"cgram", mt.snesCgRam}, {"sram", mt.snesSaveRam} }) do
    local n = emu.getMemorySize(r[2])
    for base = 0, n - 1, 4096 do
      local t = {}
      for a = base, math.min(base + 4095, n - 1) do
        t[#t + 1] = string.format("%02x", emu.read(a, r[2]))
      end
      print(string.format("[rcdump] %s %06x %s", r[1], base, table.concat(t)))
    end
  end
  local st = emu.getState()
  local keys = {}
  for k in pairs(st) do keys[#keys + 1] = k end
  table.sort(keys)
  for _, k in ipairs(keys) do print("[rcstate] " .. k .. "=" .. tostring(st[k])) end
end

emu.addEventCallback(function()
  frame = frame + 1
  while PADS[pi] and PADS[pi][1] <= frame do setPad(PADS[pi][2]); pi = pi + 1 end
  while LOADS[li] and LOADS[li][1] <= frame do
    pendingLoad = b64decode(LOADS[li][2]); li = li + 1
    print("[rcreplay] load requested at frame " .. frame .. " (" .. #pendingLoad .. " bytes)")
    execRef = emu.addMemoryCallback(function()
      if pendingLoad then
        local blob = pendingLoad
        pendingLoad = nil
        emu.loadSavestate(blob)
      end
    end, emu.callbackType.exec, 0x000000, 0xFFFFFF)
  end
  if execRef and not pendingLoad then
    emu.removeMemoryCallback(execRef, emu.callbackType.exec, 0x000000, 0xFFFFFF)
    execRef = nil
  end
  if frame % 4096 == 0 then print("[rcreplay] frame " .. frame) end
  if frame % 512 == 0 then
    -- mid-run checkpoint: a hash of every emulated memory plus the CPU/SPC
    -- clocks, so a divergence is caught where it happens, not only at the end
    local mt = emu.memType
    local parts = {}
    for _, r in ipairs({ {"wram", mt.snesWorkRam}, {"aram", mt.spcRam},
                         {"vram", mt.snesVideoRam}, {"oam", mt.snesSpriteRam},
                         {"cgram", mt.snesCgRam} }) do
      local h = 2166136261
      for a = 0, emu.getMemorySize(r[2]) - 1 do
        h = ((h ~ emu.read(a, r[2])) * 16777619) & 0xFFFFFFFF
      end
      parts[#parts + 1] = string.format("%s=%08x", r[1], h)
    end
    local st = emu.getState()
    print(string.format("[rcchk] %d %s mclk=%s spcclk=%s icg=%s", frame, table.concat(parts, " "),
      tostring(st["memoryManager.masterClock"]), tostring(st["spc.cycle"]), tostring(st["ppu.internalCgramAddress"])))
  end
  if frame >= END then
    rcDump()
    print("[rcreplay] done " .. frame)
    print("[ot6] PASS (frame " .. frame .. ") replay")
    emu.stop(0)
  end
end, emu.eventType.startFrame)
print("[ot6] replay armed: " .. #PADS .. " pad changes, " .. #LOADS .. " loads, end " .. END)
''')
open(out, "w").write("".join(L))
print(f"{out}: {len(pads)} pad changes, {len(loads)} loads, end {end}")
