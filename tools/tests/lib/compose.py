def main() -> int:
    if len(sys.argv) == 2 and sys.argv[1] == "--selftest":
        return selftest()
    # --check-states: report whether anything in this tree's build/states is
    # stale.  Run by tools/worktree-setup.sh right after seeding, and by hand
    # any time a red test might not be caused by your change.
    if len(sys.argv) == 2 and sys.argv[1] == "--check-states":
        return check_states(ROOT)
    # --adopt-stamps: upgrade pre-ROM-identity stamps to the full format
    # where the tree's own records prove the missing lines (adopt_stamps).
    if len(sys.argv) == 2 and sys.argv[1] == "--adopt-stamps":
        return adopt_stamps(ROOT)
    # --sha <sidecar>: the same fingerprint the provenance lines carry, so a
    # hash seen in a run log can be checked against a state on disk.
    if len(sys.argv) == 3 and sys.argv[1] == "--sha":
        print(digest(payload(Path(sys.argv[2]))))
        return 0
    script_path, out_path = Path(sys.argv[1]), Path(sys.argv[2])
    script = script_path.read_text()
    lib = LIB.read_text()

    # Composing is not idempotent (the usage-example dofile line in the
    # inlined lib header would re-trigger inlining), so re-composition is
    # refused.
    if script.startswith(MARKER):
        print(f"error: {script_path} is already composed; refusing to re-compose")
        return 1

    # Scenario stacking: rewrite state basenames before sidecar collection,
    # so the resolver sees (and embeds) the prefixed names.  The script is
    # rewritten and the lib is not: the lib's own .mss mentions are
    # documentation, and rewriting the lib would make the composed lib differ
    # per prefix with no change in behavior.
    stack = os.environ.get("OT6_STACK", "")
    if stack:
        script = stack_rewrite(script, stack)
        print(f"stack prefix {stack!r} applied to {script_path}")

    # Collect referenced savestate sidecars: any "<path>.mss.lua" string
    # literal in the script (scripts typically bind them to a STATE local).
    # resolve_sidecar() owns the precedence; see its docstring.
    states, sources = {}, {}
    for ref in dict.fromkeys(re.findall(r'"([^"]+\.mss\.lua)"', script)):
        try:
            p = resolve_sidecar(ref, ROOT)
        except CrossTree as why:
            # Print the exception's own text too: resolve_sidecar distinguishes
            # several refusals (absolute literal, .. escape, nested checkout)
            # and only it knows which one fired.
            print(f"error: {script_path} references {ref} [{why}], which "
                  f"exists only OUTSIDE this tree ({ROOT}).  Refusing to compose another "
                  f"tree's savestate: it was generated from a different ROM, "
                  f"so a run against it proves nothing.  Generate it here "
                  f"(make, or the generator that emits it), or seed this tree "
                  f"with tools/worktree-setup.sh.")
            return 1
        if p is None:
            continue
        b64 = payload(p)
        if b64:
            states[Path(ref).name], sources[Path(ref).name] = b64, p

    # Record which sidecar was embedded, in the composed file itself.  A
    # state mismatch otherwise looks like a ROM bug: the run loads a fixture
    # that is wrong in a small way and fails somewhere unrelated, with
    # nothing naming the file it came from.  The print() lands in the run
    # log and the comment stays in the composed artifact for later
    # inspection.
    # The runtime write gate.  Armed per script by the same waiver registry
    # the static checker enforces: a file with no waivers is declared not to
    # write, and the prologue enforces that at runtime too.  A script from
    # outside the tree (a scratch probe) has no waivers by construction and
    # is always gated.
    waived_files = load_write_waivers(WAIVERS)
    try:
        rel = str(script_path.resolve().relative_to(ROOT)).replace(os.sep, "/")
    except ValueError:
        rel = script_path.name
    gated = rel not in waived_files
    lib_alias = any(w.startswith("tools/tests/lib/") for w in waived_files)

    preamble = [MARKER + "\n"]
    # Coverage flag.  Mesen's Lua sandbox blocks os.getenv
    # (AllowIoOsAccess=false), so a runtime toggle cannot be read from the
    # environment inside a script; inject it as a global the way OT6_SYMS and
    # OT6_STATES are.  Set only when OT6_COVERAGE is in this compose's
    # environment, so lib/ot6.lua's coverageFlush stays a no-op otherwise.
    if os.environ.get("OT6_ACTION_TRACE") == "1":
        preamble.append("OT6_ACTION_TRACE = true\n")
    # The segment runner's knobs (lib/ot6.lua).  Mesen's Lua cannot read the
    # environment, so they ride the preamble like OT6_SYMS does:
    #   OT6_SCRIPT      which script this is; `gen_*` means a segment, which
    #                   is what turns retries and the watchdogs on by default
    #   OT6_RETRIES     attempts allowed, overriding the default and the
    #                   script's own opts.retries (seed_sweep.py sets 1)
    #   OT6_SEED_SHIFT  idle frames at the boot point before the body walks
    #                   on: the sweep's per-seed offset
    #   OT6_WATCHDOG    1/0 to force the fast-failure watchdogs on or off
    #   OT6_SHIFT_PROBE stride: run the body to its first battle once per
    #                   shift across one 60-frame period and log each first
    #                   battle's RNG key (#208; seed_sweep.py --probe)
    preamble.append('OT6_SCRIPT = "%s"\n' % script_path.stem)
    for var, name in (("OT6_RETRIES", "OT6_RETRIES"),
                      ("OT6_SEED_SHIFT", "OT6_SEED_SHIFT"),
                      ("OT6_SHIFT_PROBE", "OT6_SHIFT_PROBE"),
                      ("OT6_WATCHDOG", "OT6_WATCHDOG")):
        raw = os.environ.get(var)
        if raw is None or raw == "":
            continue
        try:
            preamble.append("%s = %d\n" % (name, int(raw)))
        except ValueError:
            print(f"error: {var}={raw!r} is not an integer")
            return 1
    if os.environ.get("OT6_COVERAGE"):
        preamble.append("OT6_COVERAGE = true  -- lib/ot6.lua coverageFlush (#130)\n")
    # The SRAM checkpoint run.sh installed for this run, if any (#217).  A
    # script that boots differently depending on whether it was handed a
    # checkpoint cannot read the environment -- os.getenv is nil under
    # Mesen's sandbox, so `os.getenv("OT6_SRAM_CHECKPOINT")` silently
    # answers "no checkpoint" on a run that has one, and gen_thamasa_arrive
    # loaded a savestate on a by-hand checkpoint re-cut.  Pass it the same
    # way the runner's own knobs are passed: as a preamble global, its value
    # the checkpoint directory exactly as it appeared in the environment.
    ck = os.environ.get("OT6_SRAM_CHECKPOINT")
    if ck:
        preamble.append('OT6_SRAM_CHECKPOINT = %s  -- the checkpoint run.sh '
                        'installed (#217)\n'
                        % ('"%s"' % ck.replace("\\", "\\\\").replace('"', '\\"')))
    if gated:
        preamble += write_gate_prologue()
    else:
        preamble.append(f"-- runtime write gate OFF: {rel} still carries "
                        f"state-write waivers (registry; "
                        f"tools/state_write_waivers.txt)\n")
    if states:
        for name, b64 in states.items():
            preamble.append(f"-- state {name} sha={digest(b64)} "
                            f"({len(b64)} b64 chars) <- {sources[name]}\n")
        preamble.append("OT6_STATES = {\n")
        for name, b64 in states.items():
            preamble.append(f'  ["{name}"] = "{b64}",\n')
        preamble.append("}\n")
        for name, b64 in states.items():
            preamble.append(f'print("[ot6] state {name} sha={digest(b64)} '
                            f'<- {sources[name]}")\n')
        # Warn if an embedded fixture no longer matches the generator+lib it
        # was generated from.  Non-fatal: the print lands in the [ot6] log.
        # Also record it in a table the lib can read, so a wait that times
        # out can name the fixture it booted and report that the fixture was
        # already known-stale, since the failure line ("timeout waiting for
        # main menu") does not otherwise say so.  See M.timeoutContext in
        # lib/ot6.lua.
        flagged = {}
        for name in states:
            verdict, msg = stamp_status(name, ROOT)
            if verdict == DRIFT:
                # Provenance only: the fixture verifies against this ROM and
                # its generator; the shared lib halves moved since it was
                # made.  Recorded in the log, not a warning, not OT6_STALE.
                preamble.append(f"-- NOTE: {msg}\n")
                preamble.append(f'print("[ot6] provenance: {msg}")\n')
                continue
            stale = msg if verdict in (STALE, UNBOUND, UNVERIFIED) else None
            if stale:
                flagged[name] = stale
                preamble.append(f"-- WARNING (issue #2): {stale}\n")
                preamble.append(f'print("[ot6] WARNING: {stale}")\n')
                print(f"WARNING: {stale}")
        if flagged:
            preamble.append("OT6_STALE = {\n")
            for name, stale in flagged.items():
                preamble.append(f'  ["{name}"] = "{stale}",\n')
            preamble.append("}\n")

    # OT6 symbol addresses: derive them from this tree's ff6-en.dbg the same
    # way OT6_STATES embeds sidecars.  Only symbols named via H.sym("...")
    # are collected, so the injection is inert for a tree that names none
    # (no reference -> no table emitted).  See ot6.lua M.sym for the
    # accessor and the error on a missing symbol.
    #
    # The scan covers the libs as well as the test, because the libs are
    # inlined into every composed script and so can call H.sym exactly as a
    # test can.  Over-collecting is inert -- an unused entry costs one table
    # row -- so the price of the wider scan is that every composed script
    # now carries the union of the names the libs mention.
    sym_text = "\n".join([script, lib, FIELD.read_text(),
                          CONTRACT.read_text()])
    sym_names = list(dict.fromkeys(_SYM_REF.findall(sym_text)))
    if sym_names:
        syms, ambig = parse_dbg_syms(DBG, sym_names)
        preamble.append(f"-- OT6 symbols from {DBG} (via lib/compose.py)\n")
        preamble.append("OT6_SYMS = {\n")
        for name in sym_names:
            if name in syms:
                preamble.append(f'  ["{name}"] = 0x{syms[name]:06X},\n')
        preamble.append("}\n")
        # A named-but-unresolved symbol is a non-fatal warning here; the
        # failure comes from H.sym raising at runtime (an unbuilt ROM, or a
        # mistyped name).  Matches how a missing sidecar defers to loadState.
        for name in sym_names:
            if name not in syms and name not in ambig:
                msg = (f"symbol {name} not found in ff6/rom/ff6-en.dbg "
                       f"-- rebuild the ROM, or check the name")
                preamble.append(f'print("[ot6] WARNING: {msg}")\n')
                print(f"WARNING: {msg}")
        # An ambiguous name is fatal rather than deferred: a duplicated name
        # cannot be guessed at safely, so composition stops and names the
        # choices.
        #
        # The exception is a name whose every occurrence is inside a comment.
        # The ref collector over-collects from prose (see _SYM_REF), and
        # probe_dottick.lua's header documents this hazard by spelling out
        # `H.sym("ExecCmd")`.  A doc comment must not fail a build, so a
        # comment-only ambiguity is recorded in OT6_SYMS_AMBIG instead, and
        # H.sym raises the same message if the name is called.
        if ambig:
            # over the same text the names were collected from, so a live
            # call in a lib is not mistaken for prose in the test
            inert = set(comment_only_refs(sym_text, ambig))
            for name, cands in sorted(ambig.items()):
                where = ", ".join(f"{s}=0x{a:06X}" for s, a in cands)
                msg = (f"symbol {name} is AMBIGUOUS in ff6/rom/ff6-en.dbg "
                       f"({where}) -- name the segment you mean, e.g. "
                       f'H.sym("{name.split("@")[0]}@{cands[0][0]}")')
                if name in inert:
                    preamble.append(f'  -- ambiguous: {msg}\n')
                else:
                    print(f"error: {script_path}: {msg}")
            live = {n: c for n, c in ambig.items() if n not in inert}
            if live:
                return 1
            preamble.append("OT6_SYMS_AMBIG = {\n")
            for name, cands in sorted(ambig.items()):
                where = ", ".join(f"{s}=0x{a:06X}" for s, a in cands)
                preamble.append(f'  ["{name}"] = "{where}",\n')
            preamble.append("}\n")

    composed, replaced = inline_libs(script, lib, FIELD.read_text(),
                                     CONTRACT.read_text(),
                                     raw_alias=lib_alias)
    if not replaced:
        # script doesn't use the lib (e.g. smoke.lua); pass it through, marked
        out_path.write_text(MARKER + "\n" + script)
        print(f"composed {out_path} (no lib reference; copied as-is)")
        return 0

    out_path.write_text("".join(preamble) + composed)
    print(f"composed {out_path} ({len(states)} embedded savestate(s))")
    for name, b64 in states.items():
        print(f"  {name} sha={digest(b64)} <- {sources[name]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
