#!/usr/bin/env python3
"""Compose a self-contained Lua test file for Mesen's testrunner: inlines the
test library (lib/ot6.lua, lib/ot6_field.lua, lib/ot6_contract.lua) and any
savestate sidecars a script references into one file that does no file
access at run time, since Mesen's default AllowIoOsAccess=false setting
makes runtime dofile()/loadfile() fail.

Transformations:
  1. `local H = dofile(".../lib/ot6.lua")` is replaced by the two lib
     halves; see inline_libs() for the shape.  Every script gets both.
  2. For every `H.loadState("<path>.mss.lua")` reference whose sidecar file
     exists, the sidecar's base64 payload is embedded into a global table
     `OT6_STATES[basename]`; the lib's loadState() checks that table first.
     The sidecar is taken from this tree's build/states whenever it has
     one, and every embedded state is named, with a short hash, in a
     comment and a print() at the head of the composed file.

Usage: compose.py <script.lua> <out.lua>

SCENARIO STACKING: `OT6_STACK=<prefix>` rewrites the basename of every
`.mss`/`.mss.lua` string literal in the script (never in the lib) at
compose time, so `OT6_STACK=t2_` composes gen_rapids into a script that
boots t2_scenario_hub.mss.lua and emits t2_rapids_*.mss.
"""
import hashlib
import contextlib
import importlib.util
import io
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE / "ot6.lua"            # battle core; yields the module table
FIELD = HERE / "ot6_field.lua"    # nav half; installs onto that same table
CONTRACT = HERE / "ot6_contract.lua"  # checkpoint entry/exit contracts
SAVESTATE_STAMP = HERE / "savestate_stamp.sh"  # the one definition of the generator sig
ROOT = HERE.parent.parent.parent           # lib/ -> tests/ -> tools/ -> tree root
MARKER = "-- AUTOGENERATED by lib/compose.py; edit the source script instead."
# The ca65 debug file for this tree's ROM.  Any symbol a script names via
# H.sym("Name") is looked up in this file and injected as OT6_SYMS, the same
# mechanism OT6_STATES uses for savestate sidecars.  A test that needs a
# symbol before the ROM is built fails at H.sym with a named error (see
# ot6.lua).
#
# `OT6_DBG` overrides it, and is the symbol-side twin of run.sh's `OT6_ROM`:
# an A/B arm that boots a differently-assembled ROM (the OT6_MP_COSTS=0 /
# OT6_BOOST_PRICE=0 controls) must read THAT ROM's symbols, because a flag
# that adds or drops one byte moves every label after it.  Setting one
# without the other is how an observer ends up hooked at a stale address.
DBG = Path(os.environ.get("OT6_DBG") or (ROOT / "ff6" / "rom" / "ff6-en.dbg"))
# The state-write waiver registry (tools/check_state_writes.py defines the
# format).  Composition reads it to decide, per script, whether to arm the
# runtime write gate below.
WAIVERS = ROOT / "tools" / "state_write_waivers.txt"


def declared_states(root):
    """Fixture names in this tree's current savestate graph, the also=
    siblings a generator run publishes included.  An unreadable or absent
    graph returns the empty-set fallback."""
    return set(_graph_order(root))


def _graph_order(root):
    """Fixture names in play order, also= siblings right after their state;
    [] when the graph is unreadable or absent."""
    path = Path(root) / "tools" / "tests" / "savestate_graph.py"
    try:
        spec = importlib.util.spec_from_file_location("savestate_graph", path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        out = []
        for e in mod.STATES:
            out.append(e["state"])
            out += list(e.get("also") or [])
        return out
    except Exception:
        return []


def load_write_waivers(path):
    """The set of repo-relative paths carrying at least one state-write
    waiver.  Only the path column is read; the runtime gate is per script."""
    waived = set()
    if path.exists():
        for line in path.read_text().splitlines():
            if line.startswith("#") or not line.strip():
                continue
            waived.add(line.split("\t", 1)[0].strip())
    return waived


# The write-side emu surface, kept in sync with check_state_writes.py's
# TOKENS (the emu.* half; the .writeByte(/H.write/M.write wrapper tokens are
# lib entry points, which are removed with the lib's own waiver registry instead).
WRITE_GATE_SURFACE = [
    "write", "writeWord", "write16", "write32",
    "setState", "addCheat", "clearCheats",
    "rewind", "reset", "loadSavestate",
]


def write_gate_prologue():
    """The runtime half of the no-state-writes rule: runs before any user or
    lib code, captures the real `emu` in a file-local, then replaces the
    global with a proxy whose write surface raises an error.  Read-side
    calls pass through untouched.  Scripts whose file still carries
    state-write waivers compose without the prologue."""
    lines = [
        "-- RUNTIME WRITE GATE (issue #75): this script's file carries no\n",
        "-- state-write waivers, so the write-side emu surface is refused at\n",
        "-- runtime too. Snapshot helpers remain permitted (docs/TESTING.md).\n",
        "local __OT6_EMU_RAW = emu\n",
        "do\n",
        "  local proxy = setmetatable({}, { __index = __OT6_EMU_RAW })\n",
    ]
    for name in WRITE_GATE_SURFACE:
        lines.append(
            '  proxy.%s = function()\n'
            '    error("[ot6] runtime write gate (issue #75): emu.%s is '
            'forbidden here -- use snapshot helpers for complete restores; '
            'no selective gameplay edits (docs/TESTING.md)", 2)\n'
            '  end\n' % (name, name))
    lines += [
        "  emu = proxy\n",
        "end\n",
    ]
    return lines


def payload(sidecar: Path) -> str:
    """The base64 blob out of a `return "<b64>"` sidecar ("" if malformed)."""
    m = re.search(r'return\s+"([A-Za-z0-9+/=]+)"', sidecar.read_text())
    return m.group(1) if m else ""


def digest(b64: str) -> str:
    """Short fingerprint of an embedded payload, for the provenance lines.
    Hashes the base64 text rather than the sidecar file, so it can be
    recomputed from either side, a composed file or a sidecar."""
    return hashlib.sha256(b64.encode()).hexdigest()[:12]


def _stamp_tool(root, *args, check=True, env=None):
    """Shell into savestate_stamp.sh, the single authority for every digest
    a stamp carries, pointed at `root` via OT6_ROOT.  Returns stdout, or
    None when check=False and the tool refused (e.g. romsig with no ROM).
    `env` adds to (or overrides) the inherited environment."""
    r = subprocess.run(
        ["sh", str(SAVESTATE_STAMP), *args],
        env={**os.environ, "OT6_ROOT": str(root), **(env or {})},
        capture_output=True, text=True, check=check,
    )
    return r.stdout if r.returncode == 0 else None


def generator_sig(gen, root, extras=()):
    """The provenance sig, sha256(GATE_CONTRACT ++ generator ++ the three
    lib halves ++ extras): savestate_stamp.sh's `sig`, the same digest the
    `generate` edge wrote into the stamp's first line."""
    out = _stamp_tool(root, "sig", gen, *extras)
    return out.split()[0]            # "<64-hex> <gen>" -> the digest half


def generator_own_sig(gen, root, extras=()):
    """The compatibility binding for the generator: sha256(GATE_CONTRACT ++
    generator ++ extras), the lib halves left out (`gensig`)."""
    return _stamp_tool(root, "gensig", gen, *extras).strip()


def rom_identity(root):
    """The sha256 of the ROM a run in this tree boots (`romsig`: OT6_ROM if
    set, else build/ot6.sfc), and the path it named.  (None, path) when no
    ROM is there to hash: the checker then reports UNVERIFIED rather than
    guessing."""
    path = os.environ.get("OT6_ROM") or "build/ot6.sfc"
    out = _stamp_tool(root, "romsig", check=False)
    return (out.strip() if out else None), path


# Verdicts stamp_status() can return, in the order it decides them.
FRESH, DRIFT, STALE, UNBOUND, UNVERIFIED = (
    "fresh", "drift", "stale", "unbound", "unverified")


def stamp_status(name, root, _memo=None):
    """Consume-time compatibility and provenance check for a generated
    fixture.  Returns (verdict, message): (None, None) when there is nothing
    to check (no stamp, or a generator since removed); (FRESH, None) when
    every binding verifies; (DRIFT, note) when the fixture still verifies
    but was produced by older shared lib halves (informational -- see
    docs/TESTING.md, "Provenance and compatibility"); otherwise a STALE /
    UNBOUND / UNVERIFIED verdict with the line `--check-states` fails on.

    savestate_stamp.sh's header defines the stamp format.  The bindings and
    the rule each is held to:

      compatibility (decides freshness):
        `rom <sha256>`        the ROM the run booted.  Changed ROM
                              code/layout can invalidate a machine
                              snapshot, so a different ROM is STALE; no
                              ROM on disk to compare is UNVERIFIED.
        `generator <sha256>`  the generator's own sig (extras included,
                              lib halves excluded).  The play that reached
                              the state changed: STALE.
        `artifact <sha256>`   the .mss beside the stamp: replaced bytes
                              are UNBOUND.
        `ancestor <path> <sha256>`  the stamp or checkpoint manifest this
                              state grew from: a moved chain is STALE.
      provenance (recorded, reported, never a stale verdict by itself):
        `<sig> <gen> [extras]` the sig over gen+lib halves+extras, and
        `lib <path> <sha256>`  each lib half's bytes at generation time.
                              A logging, assertion or controller-policy
                              edit shared by every generator does not make
                              a legitimately reached snapshot illegitimate;
                              it is reported as DRIFT.

    Migration: a stamp written before the rom/generator lines existed has
    neither.  Nothing is invented for it; it stays on the older conservative
    rule -- the whole sig must match -- until the fixture is regenerated,
    which writes the full format, or until `compose.py --adopt-stamps`
    (adopt_stamps below) proves from the tree's own records what the
    missing lines would say and appends them.

    Transitivity (#212): a fixture whose own bindings all verify but whose
    `ancestor` stamp is itself STALE or UNBOUND is STALE too, naming the
    chain from its ancestor down to the link that moved (`STALE via
    dadaluma_entry <- zozo_arrival`: dadaluma_entry was generated from a
    zozo_arrival that has since been regenerated).  The descendant's bytes
    are exactly what its stamp vouches for, but they grew from a state that
    is no longer the tree's, so the chain below the moved link is stale all
    the way down -- the same set ninja regenerates, since every prev= edge
    depends on its parent's outputs.  Only a build/states stamp ancestor is
    followed; a checkpoint manifest is its own binding.  A DRIFT or
    UNVERIFIED ancestor passes nothing down, so a lib-only edit still stales
    no descendant.  `_memo` lets a whole-tree caller check each stamp once.
    """
    base = name[:-len(".mss.lua")] if name.endswith(".mss.lua") else name
    verdict, msg, _ = _stamp_status(base, Path(root),
                                    {} if _memo is None else _memo)
    return verdict, msg


def _stamp_status(base, root, memo):
    """stamp_status() for one base name, plus its chain: [] when the verdict
    is the fixture's own (or there is nothing wrong), else the stamp names
    from its ancestor down to the link that moved.  A STALE verdict from a
    failed ancestor binding has the one-link chain [ancestor].  memo doubles
    as the cycle guard (a cycle reads as nothing to inherit)."""
    if base in memo:
        return memo[base] or (None, None, [])
    memo[base] = None
    verdict, msg = _own_stamp_status(base, root)
    chain = []
    anc = _stamp_ancestor(base, root)
    if verdict == STALE and msg and "the chain below it moved" in msg:
        chain = [anc] if anc else []
    elif verdict in (FRESH, DRIFT) and anc:
        a_verdict, a_msg, a_chain = _stamp_status(anc, root, memo)
        if a_verdict in (STALE, UNBOUND):
            chain = [anc] + a_chain
            last = (memo.get(chain[-1]) or (None,))[0]
            why = (f"{chain[-1]} is itself {last.upper()}"
                   if last in (STALE, UNBOUND)
                   else f"{chain[-2]} was generated from a {chain[-1]} that "
                        f"has since moved")
            verdict, msg = STALE, (
                f"fixture {base} is STALE via {' <- '.join(chain)} -- its "
                f"own bindings verify, but it grew from a chain that is no "
                f"longer this tree's ({why}); regenerate: ninja "
                f"build/states/{base}.mss.lua (issue #212)")
    memo[base] = (verdict, msg, chain)
    return verdict, msg, chain


def _stamp_ancestor(base, root):
    """The build/states stamp this fixture's `ancestor` line names, as a base
    name; None for no stamp, no ancestor, or a checkpoint manifest."""
    try:
        lines = (root / "build" / "states" / (base + ".stamp")).read_text() \
            .splitlines()
    except OSError:
        return None
    for line in lines[1:]:
        parts = line.split()
        if len(parts) >= 2 and parts[0] == "ancestor":
            m = re.fullmatch(r"build/states/([^/]+)\.stamp", parts[1])
            return m.group(1) if m else None
    return None


def _own_stamp_status(base, root):
    """stamp_status() without the transitive step: this fixture's own
    bindings only."""
    stamp = root / "build" / "states" / (base + ".stamp")
    if not stamp.exists():
        return None, None
    lines = stamp.read_text().splitlines()
    head = lines[0].split() if lines else []
    if len(head) < 2:
        return None, None
    recorded, gen, *extras = head
    gen_lua = root / "tools" / "tests" / (gen + ".lua")
    if not gen_lua.exists():
        return None, None
    regen = f"regenerate it: ninja build/states/{base}.mss.lua"

    fields = {}
    libs = []
    for line in lines[1:]:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "lib" and len(parts) == 3:
            libs.append((parts[1], parts[2]))
        else:
            fields[parts[0]] = parts[1:]

    cur = generator_sig(gen, root, extras)
    rom = fields.get("rom")
    own = fields.get("generator")
    if not (rom and own):
        # Pre-ROM-identity stamp: the conservative rule, exactly as before
        # the rom/generator lines existed.
        if cur != recorded[:64]:
            return STALE, (
                f"fixture {base} is STALE -- generated from {gen}+lib sha "
                f"{recorded[:12]}, current script hashes {cur[:12]}; its "
                f"stamp predates ROM-identity recording, so it is held to "
                f"the conservative whole-sig rule until regenerated; {regen}")
        drift = None
    else:
        have, rom_path = rom_identity(root)
        if have is None:
            return UNVERIFIED, (
                f"fixture {base} is UNVERIFIED -- it was generated on ROM "
                f"sha {rom[0][:12]} but this tree has no {rom_path} to "
                f"compare against; build it (ninja build/ot6.sfc) and "
                f"re-check")
        if have != rom[0]:
            return STALE, (
                f"fixture {base} is STALE -- generated on ROM sha "
                f"{rom[0][:12]}, but {rom_path} is sha {have[:12]}: a "
                f"machine snapshot of a different ROM; {regen}")
        cur_own = generator_own_sig(gen, root, extras)
        if cur_own != own[0]:
            return STALE, (
                f"fixture {base} is STALE -- its generator {gen} changed "
                f"(own sha {own[0][:12]} at generation, {cur_own[:12]} now"
                f"{', extras included' if extras else ''}); {regen}")
        drift = None
        if cur != recorded[:64]:
            moved = [p for p, h in libs
                     if (root / p).exists()
                     and hashlib.sha256((root / p).read_bytes()).hexdigest()
                     != h]
            what = (", ".join(p.split("/")[-1] for p in moved)
                    if moved else "the shared lib halves")
            drift = (f"fixture {base} has provenance drift -- generated "
                     f"with {gen}+lib sha {recorded[:12]}, current sources "
                     f"hash {cur[:12]}: lib/{what} moved since generation. "
                     f"ROM and generator match, so it stays a valid "
                     f"snapshot (docs/TESTING.md); regenerate only if the "
                     f"lib change should be reflected in the fixture")

    art = fields.get("artifact")
    if not art:
        return UNBOUND, (
            f"fixture {base} is UNBOUND -- its stamp predates the "
            f"provenance format (no artifact line) so nothing ties the "
            f".mss bytes to the run that claims them; re-run "
            f"regenerate: ninja build/states/{base}.mss.lua")
    mss = root / "build" / "states" / (base + ".mss")
    if not mss.exists():
        return UNBOUND, (
            f"fixture {base} is UNBOUND -- its stamp exists but "
            f"build/states/{base}.mss does not; regenerate: ninja "
            f"to regenerate it (issue #75)")
    actual = hashlib.sha256(mss.read_bytes()).hexdigest()
    if actual != art[0]:
        return UNBOUND, (
            f"fixture {base} is UNBOUND -- build/states/{base}.mss "
            f"(sha {actual[:12]}) is not the artifact its stamp vouches "
            f"for (sha {art[0][:12]}): the state was replaced without a "
            f"generation run; regenerate: ninja build/states/{base}.mss.lua "
            f"(issue #75)")

    anc = fields.get("ancestor")
    if anc:
        if len(anc) < 2:
            return UNBOUND, (
                f"fixture {base} is UNBOUND -- its stamp's ancestor "
                f"line is malformed; regenerate: ninja build/states/{base}.mss.lua")
        path, digest_ = anc[0], anc[1]
        anc_file = root / path
        if not anc_file.exists():
            return UNBOUND, (
                f"fixture {base} is UNBOUND -- its ancestor {path} is "
                f"gone, so the chain it was generated from cannot be "
                f"verified; regenerate: ninja build/states/{base}.mss.lua")
        anc_actual = hashlib.sha256(anc_file.read_bytes()).hexdigest()
        if anc_actual != digest_:
            return STALE, (
                f"fixture {base} is STALE -- its ancestor {path} "
                f"(sha {anc_actual[:12]}) is not the one it was "
                f"generated from (sha {digest_[:12]}); the chain below "
                f"it moved; regenerate: ninja build/states/{base}.mss.lua "
                f"(issue #75)")
    if drift:
        return DRIFT, drift
    return FRESH, None


def stamp_check(name, root):
    """The failing half of stamp_status(): the message for a STALE, UNBOUND
    or UNVERIFIED fixture, None for a fresh one or one with only provenance
    drift.  This is the line the composed file prints through the [ot6]
    channel and that `--check-states` fails on."""
    verdict, msg = stamp_status(name, root)
    return msg if verdict in (STALE, UNBOUND, UNVERIFIED) else None


def check_states(root):
    """`compose.py --check-states`: the same freshness question stamp_check()
    answers, asked of the whole fixture set at once instead of one sidecar at
    a time, using the same code path so there is one definition of fresh.

    Exit 0 = every stamped fixture matches its sources; 1 = some do not.
    """
    states = root / "build" / "states"
    all_stamps = sorted(states.glob("*.stamp"))
    declared = declared_states(str(root))
    # build/states outlives the graph: renames leave the old artifact and
    # stamp behind forever.  Those files are not fixtures any more and may
    # name checkpoint inputs that no longer exist.
    if declared:
        stamps = [s for s in all_stamps if s.stem in declared]
        orphans = [s for s in all_stamps if s.stem not in declared]
    else:
        # An unreadable graph means "cannot tell", so check everything
        # rather than silently skip.
        stamps, orphans = all_stamps, []
    if not stamps:
        print("no generated fixtures in this tree "
              "(none declared; build/states is unseeded); "
              "tests that need a generated savestate will report SKIPPED, "
              "not fail")
        return 0
    stale, drift = [], []
    legacy = 0                      # stamps with no rom/generator lines
    memo = {}
    for s in stamps:
        verdict, msg = stamp_status(s.stem, root, memo)
        if verdict in (STALE, UNBOUND, UNVERIFIED):
            stale.append((s.stem, msg))
        elif verdict == DRIFT:
            drift.append((s.stem, msg))
        if not any(l.startswith("rom ") for l in s.read_text().splitlines()):
            legacy += 1
    tail = ""
    if orphans:
        tail += f"; {len(orphans)} obsolete build stamp(s) ignored"
    if legacy:
        tail += (f"; {legacy} stamp(s) predate ROM-identity recording and "
                 f"are held to the conservative whole-sig rule until "
                 f"regenerated or adopted (compose.py --adopt-stamps)")
    if not stale:
        print(f"fixtures: {len(stamps)}/{len(stamps)} fresh "
              f"(ROM, generator, artifact and ancestor bindings all verify)"
              + tail)
        if drift:
            # Informational: the fixture is still a valid snapshot of this
            # ROM reached by this generator; only the shared harness that
            # produced it has moved since (docs/TESTING.md).
            halves = {}
            for _, msg in drift:
                for h in (LIB.name, FIELD.name, CONTRACT.name):
                    if h in msg:
                        halves[h] = halves.get(h, 0) + 1
            named = ", ".join(f"lib/{h} ({n})" for h, n in sorted(halves.items()))
            print(f"provenance drift (informational, not stale): "
                  f"{len(drift)} of {len(stamps)} were generated with older "
                  f"shared lib halves -- {named or 'lib halves'} moved since. "
                  f"ROM and generator match, so they remain valid snapshots; "
                  f"regenerate only if the lib change should be reflected "
                  f"in the fixtures.")
            print(f"  {drift[0][1]}")
            if len(drift) > 1:
                print(f"  ... and {len(drift) - 1} more, same shape")
        return 0
    verdicts = {}
    for _, msg in stale:
        kind = msg.split(" is ", 1)[1].split(" ", 1)[0]
        verdicts[kind] = verdicts.get(kind, 0) + 1
    summary = ", ".join(f"{n} {k}" for k, n in sorted(verdicts.items()))
    print(f"fixtures: {len(stale)} of {len(stamps)} do not verify "
          f"({summary}) -- generated on another ROM or by a changed "
          f"generator, carrying bytes their stamps do not vouch for, or "
          f"unverifiable in this tree{tail}.")

    # Name the one cause when there is one.  Every fixture is a snapshot of
    # the same ROM, so a ROM change stales all of them at once; that case
    # looks like many separate problems but is one.
    on_other_rom = sum(1 for _, m in stale if "a machine snapshot of a "
                       "different ROM" in m)
    if on_other_rom:
        print(f"CAUSE: the ROM changed since the last generation run "
              f"({on_other_rom} of {len(stamps)} were generated on a "
              f"different ROM).  A machine snapshot belongs to the ROM it "
              f"was captured on; that is one cause"
              + (f", not {on_other_rom} separate problems."
                 if on_other_rom > 1 else "."))
    unverified = sum(1 for _, m in stale if " is UNVERIFIED " in m)
    if unverified:
        print(f"CAUSE: this tree has no built ROM to compare against "
              f"({unverified} of {len(stamps)} are UNVERIFIED, not known "
              f"stale).  ninja build/ot6.sfc, then re-check.")
    inherited = sum(1 for _, m in stale if " is STALE via " in m)
    if inherited:
        print(f"CAUSE: {inherited} of {len(stamps)} are stale only through "
              f"their chain: each one's own bindings verify, but an "
              f"ancestor it grew from is stale or was regenerated after it "
              f"(the `via` chain names the link that moved).  Regenerating "
              f"a descendant regenerates the chain above it.")
    held = sum(1 for _, m in stale if "predates ROM-identity recording" in m)
    if held:
        print(f"CAUSE: {held} of {len(stamps)} carry pre-ROM-identity "
              f"stamps, so a shared lib-half edit still stales them under "
              f"the conservative whole-sig rule.  Regenerating writes the "
              f"full stamp format, after which only the ROM, the "
              f"generator, and the artifact/ancestor bindings decide.  "
              f"Before the next lib edit, `compose.py --adopt-stamps` "
              f"upgrades a legacy stamp in place when the tree's own "
              f"records prove the missing lines (it refuses these, whose "
              f"sig has already moved).")

    show = 6
    for _, msg in stale[:show]:
        print(f"  {msg}")
    if len(stale) > show:
        print(f"  ... and {len(stale) - show} more, same shape")
    if drift:
        print(f"provenance drift (informational, not stale) on {len(drift)} "
              f"fixture(s) besides: shared lib halves moved since "
              f"generation; ROM and generator match.")

    # Name the smallest sufficient action: a stale fixture only matters for
    # the tests that embed it, and regenerating one step is minutes where
    # the full chain is hours.
    print("\nA test that boots one of these can be red for a reason that has "
          "nothing to do with your change.\nRegenerate just what you need:  "
          "nice -n 10 ninja -f build/build.ninja <state>\nor the whole chain: "
          " nice ninja")
    return 1


# ------------------------------------------------- legacy stamp adoption --
# `compose.py --adopt-stamps`: upgrade a pre-ROM-identity stamp (sig,
# artifact and ancestor lines only) to the full format, but ONLY when the
# tree's own records prove what the missing lines would say.  Nothing is
# invented; a fixture whose records do not prove it is refused and told why.
#
# The proof, per fixture (adoption_proof):
#   1. The recorded sig equals the CURRENT sig over gen + lib halves +
#      extras (savestate_stamp.sh `sig`).  Then the generator's own sig and
#      the lib-half hashes at generation time are the current ones, and can
#      be written as `generator` and `lib` lines.
#   2. The ROM at generation time equals the current ROM.  Every generate
#      edge depends on the ROM through its copy_if_changed edge
#      build/ninja/src/build/ot6.sfc (configure.py / savestate_ninja.py:
#      `cmp -s || cp`, restat = 1), so when ninja started the edge the
#      copy was byte-equal to build/ot6.sfc, the ROM run.sh boots.
#      The copy is rewritten only when the ROM's content changes, and
#      only by the copy_if_changed edge.  ninja's build log (build/ninja/.ninja_log;
#      builddir = build/ninja) records each edge run as
#      `start_ms end_ms mtime_ns output hash`: start/end are relative to
#      that ninja invocation, but the third column is absolute -- for a
#      plain edge it is the edge's start time (ninja >= 1.11 records
#      command_start_time_ there; verified on 1.13.2 / log v7 by the
#      selftest below), and for a restat edge it is the output's new mtime
#      when the command rewrote it, else the command's start time.  Either
#      way the copy's last rewrite is no later than the copy edge's most recent
#      record.  So: copy record < generate start, AND the copy's bytes are
#      the current ROM's, proves the state was generated on the current
#      ROM.  If the copy edge's most recent record is not before the generate
#      started, the records cannot tell whether the copy was rewritten
#      since, and the fixture is refused.  The stamp's own mtime must fall
#      inside the recorded edge's window, so a stamp written by a hand run
#      after that edge cannot borrow the edge's record.
#   3. The artifact line still verifies (the .mss bytes match).
#
# The new lines are inserted in the order `write` produces, the original
# sig line untouched, so stamp_status() sees a full-format stamp.  Two
# consequences are handled here rather than left to the reader:
#   - every child binds `ancestor <path> <sha256 of the parent's stamp
#     bytes>`; appending lines to the parent moves that hash, so each child
#     whose ancestor line named the parent's OLD bytes is rebound to the
#     new bytes (that is the same fact restated, not a new binding), and so
#     on down the chain;
#   - the stamp is a ninja input of every child's generate edge, so each
#     rewrite keeps the file's mtime (ninja schedules by mtime; adoption is
#     not a generation and must not look like one).

NINJA_LOG = "build/ninja/.ninja_log"          # builddir = build/ninja
NINJA_LOG_VERSIONS = ("v7",)                  # what the selftest verified
ROM_COPY = "build/ninja/src/build/ot6.sfc"   # copy_if_changed_from(ROM) in configure.py
LIB_HALVES = ("tools/tests/lib/ot6.lua", "tools/tests/lib/ot6_field.lua",
              "tools/tests/lib/ot6_contract.lua")


def ninja_log_records(root):
    """The most recent record per output in this tree's ninja build log:
    ({output: (start_ms, end_ms, mtime_ns)}, None), or (None, why) when the
    log is missing or of a version whose columns this code has not been
    verified against."""
    log = root / NINJA_LOG
    if not log.exists():
        return None, f"no ninja build log at {NINJA_LOG}"
    lines = log.read_text().splitlines()
    if not lines or not lines[0].startswith("# ninja log "):
        return None, f"{NINJA_LOG} has no ninja log header"
    version = lines[0].split()[-1]
    if version not in NINJA_LOG_VERSIONS:
        return None, (f"{NINJA_LOG} is ninja log {version}; the adoption's "
                      f"reading of its columns is verified for "
                      f"{', '.join(NINJA_LOG_VERSIONS)} only")
    records = {}
    for line in lines[1:]:
        parts = line.split("\t")
        if len(parts) < 4:
            continue
        try:
            records[parts[3]] = (int(parts[0]), int(parts[1]), int(parts[2]))
        except ValueError:
            continue
    return records, None


def _when(ns):
    import datetime
    return datetime.datetime.fromtimestamp(ns / 1e9).strftime(
        "%Y-%m-%d %H:%M:%S.%f")[:-3]


def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _rewrite_keeping_mtime(path, text):
    """Replace a stamp's bytes and put its mtime back: ninja schedules the
    children of this stamp by that mtime, and adoption is not a generation."""
    st = path.stat()
    path.write_text(text)
    os.utime(path, ns=(st.st_atime_ns, st.st_mtime_ns))


def adoption_proof(base, root, records, rom_now, rom_copy_sha):
    """Decide one fixture.  Returns ("full", None) for a stamp that already
    has the compatibility lines, ("refused", why) when the records do not
    prove the missing lines, or ("adopt", (new_text, evidence)) with the
    full-format text to write and a one-line account of the evidence.
    `records` is ninja_log_records()'s table (or None with rom_now/rom_copy_sha
    unused); `rom_now` the sha of build/ot6.sfc (None when absent);
    `rom_copy_sha` the sha of the ROM copy (None when absent)."""
    stamp = root / "build" / "states" / (base + ".stamp")
    regen = f"regenerate it: ninja build/states/{base}.mss.lua"
    lines = stamp.read_text().splitlines()
    head = lines[0].split() if lines else []
    if len(head) < 2:
        return "refused", "its stamp has no sig line to reason from"
    recorded, gen, *extras = head
    fields = {}
    for line in lines[1:]:
        parts = line.split()
        if parts:
            fields.setdefault(parts[0], []).append(parts[1:])
    if "rom" in fields and "generator" in fields:
        return "full", None
    unexpected = sorted(set(fields) - {"artifact", "ancestor"})
    if unexpected:
        return "refused", (
            f"its stamp carries {', '.join(unexpected)} line(s) but not the "
            f"full rom+generator pair: neither the legacy nor the full "
            f"format; {regen}")
    if len(fields.get("artifact", [])) != 1 or len(fields.get("ancestor", [])) > 1:
        return "refused", f"its stamp's artifact/ancestor lines are malformed; {regen}"
    gen_lua = root / "tools" / "tests" / (gen + ".lua")
    if not gen_lua.exists():
        return "refused", f"its generator tools/tests/{gen}.lua is gone"

    # 1. the sig: the current sources ARE the generation-time sources.
    cur = generator_sig(gen, root, extras)
    if cur != recorded[:64]:
        return "refused", (
            f"its sig moved: generated from {gen}+lib halves"
            f"{'+extras' if extras else ''} sha {recorded[:12]}, the current "
            f"sources hash {cur[:12]}; the generator and lib lines cannot be "
            f"derived from sources that changed; {regen}")

    # 3. the artifact (cheap, and pointless to reason about the ROM for a
    #    fixture whose bytes are not the ones the stamp vouches for).
    art = fields["artifact"][0][0]
    mss = root / "build" / "states" / (base + ".mss")
    if not mss.exists():
        return "refused", f"build/states/{base}.mss does not exist; {regen}"
    actual = _sha(mss)
    if actual != art:
        return "refused", (
            f"its artifact moved: build/states/{base}.mss is sha "
            f"{actual[:12]}, the stamp vouches for {art[:12]}; {regen}")

    # 2. the ROM, from ninja's records.
    if rom_now is None:
        return "refused", ("this tree has no build/ot6.sfc to compare the ROM "
                           "copy against; ninja build/ot6.sfc and re-run")
    if rom_copy_sha is None:
        return "refused", (f"no ROM copy at {ROM_COPY}: ninja has not "
                           f"copied the ROM in this tree")
    if rom_copy_sha != rom_now:
        return "refused", (
            f"the ROM copy {ROM_COPY} (sha {rom_copy_sha[:12]}) is not "
            f"the current ROM (sha {rom_now[:12]}): the ROM changed since "
            f"ninja last copied it, so a state generated on the copied "
            f"ROM is a snapshot of a different ROM; {regen}")
    if records is None:
        return "refused", "no usable ninja build log (see above)"
    gen_rec = records.get(f"build/states/{base}.stamp")
    if gen_rec is None:
        return "refused", (
            f"{NINJA_LOG} has no record of a generate edge producing "
            f"build/states/{base}.stamp (generated outside ninja, or the "
            f"log was not seeded with the states); {regen}")
    copy_rec = records.get(ROM_COPY)
    if copy_rec is None:
        return "refused", f"{NINJA_LOG} has no record of the ROM copy edge {ROM_COPY}"
    g_start, g_end, g_at = gen_rec
    g_dur_ns = (g_end - g_start) * 1_000_000
    written = stamp.stat().st_mtime_ns
    # The stamp is the edge's last output: written after the edge started
    # and before it ended (one second of slack for the clock granularity of
    # a copied tree).
    if not (g_at <= written <= g_at + g_dur_ns + 1_000_000_000):
        return "refused", (
            f"its stamp was written at {_when(written)}, outside the "
            f"recorded generate edge's window [{_when(g_at)}, "
            f"{_when(g_at + g_dur_ns)}]: the stamp on disk is not the one "
            f"that edge wrote (a hand run, or a copy that did not keep "
            f"mtimes); {regen}")
    l_at = copy_rec[2]
    if not l_at < g_at:
        return "refused", (
            f"the ROM copy edge {ROM_COPY} last ran at {_when(l_at)} (its most "
            f"recent record in {NINJA_LOG}), not before this state's "
            f"generate edge started at {_when(g_at)}; whether it rewrote "
            f"the ROM copy after generation cannot be told from the "
            f"records; {regen}")

    own = generator_own_sig(gen, root, extras)
    new = [lines[0], f"rom {rom_now}", f"generator {own}"]
    new += [f"lib {h} {_sha(root / h)}" for h in LIB_HALVES]
    new += [l for l in lines[1:] if l.strip()]
    evidence = (f"rom {rom_now[:12]} (ninja: generate started "
                f"{_when(g_at)}, ROM copy edge last ran {_when(l_at)}, "
                f"{(g_at - l_at) / 1e9:.3f} s earlier, and its copy is the "
                f"current ROM), generator {own[:12]}, lib halves recorded; "
                f"sig {recorded[:12]} unchanged, artifact verifies")
    return "adopt", ("\n".join(new) + "\n", evidence)


def adopt_stamps(root):
    """`compose.py --adopt-stamps`: the adoption step over every declared
    fixture, in graph order (parents before children, so a child's ancestor
    rebinding lands before the child's own adoption).  Prints one line per
    fixture and a summary.  Exit 0 when nothing was refused, 1 otherwise."""
    states = root / "build" / "states"
    all_stamps = sorted(states.glob("*.stamp"))
    declared = declared_states(str(root))
    if declared:
        order = _graph_order(root)
        stamps = [states / f"{n}.stamp" for n in order
                  if (states / f"{n}.stamp").exists()]
        stamps += [s for s in all_stamps if s.stem in declared and s not in stamps]
    else:
        stamps = all_stamps
    if not stamps:
        print("no generated fixtures in this tree; nothing to adopt")
        return 0
    records, why = ninja_log_records(root)
    if why:
        print(f"adopt: {why}")
    rom_now = _stamp_tool(root, "romsig", check=False,
                          env={"OT6_ROM": str(root / "build" / "ot6.sfc")})
    rom_now = rom_now.strip() if rom_now else None
    rom_copy = root / ROM_COPY
    rom_copy_sha = _sha(rom_copy) if rom_copy.exists() else None

    adopted, refused, full, rebound = [], [], 0, 0

    def rebind(path_rel, old, new):
        """Every stamp whose ancestor line names path_rel with the OLD
        bytes' hash is bound to the same file's NEW bytes, and its own
        children after it."""
        nonlocal rebound
        for s in all_stamps:
            text = s.read_text()
            lines = text.splitlines()
            hit = [i for i, l in enumerate(lines)
                   if l.split() == ["ancestor", path_rel, old]]
            if not hit:
                continue
            before = hashlib.sha256(text.encode()).hexdigest()
            for i in hit:
                lines[i] = f"ancestor {path_rel} {new}"
            _rewrite_keeping_mtime(s, "\n".join(lines) + "\n")
            rebound += 1
            print(f"  rebound {s.stem}: ancestor {path_rel} {old[:12]} -> "
                  f"{new[:12]} (the parent's stamp gained its adopted lines)")
            rebind(f"build/states/{s.name}", before, _sha(s))

    for s in stamps:
        verdict, detail = adoption_proof(s.stem, root, records, rom_now, rom_copy_sha)
        if verdict == "full":
            full += 1
            continue
        if verdict == "refused":
            refused.append((s.stem, detail))
            print(f"adopt {s.stem}: REFUSED -- {detail}")
            continue
        text, evidence = detail
        old = _sha(s)
        _rewrite_keeping_mtime(s, text)
        adopted.append(s.stem)
        print(f"adopt {s.stem}: ADOPTED -- {evidence}")
        rebind(f"build/states/{s.name}", old, _sha(s))

    legacy = len(adopted) + len(refused)
    print(f"adopted {len(adopted)} of {legacy} legacy stamp(s); "
          f"{len(refused)} refused; {full} already in the full format; "
          f"{rebound} ancestor line(s) rebound to adopted parents")
    if adopted:
        print("re-check with: python3 tools/tests/lib/compose.py --check-states")
    return 1 if refused else 0


class CrossTree(Exception):
    """A referenced sidecar exists only outside the composing tree."""


BODY_OPEN = ("H.segmentBody(function()  -- the segment body (lib/ot6.lua's "
             "retry runner replays this)\n")
BODY_CLOSE = "\nend)  -- H.segmentBody\n"


def inline_libs(script: str, lib: str, field: str, contract: str,
                raw_alias: bool = False):
    """Swap the script's `local H = dofile(".../lib/ot6.lua")` line for the
    lib halves, inlined:

        local H = (function()
        <lib/ot6.lua>              -- ends with `return M`
        end)()
        ;(function(...)
        <lib/ot6_field.lua>        -- first line `local M = ...` binds H
        end)(H)
        ;(function(...)
        <lib/ot6_contract.lua>     -- same shape: checkpoint contracts
        end)(H)
        H.segmentBody(function()
        <the rest of the script>
        end)

    The script's own text becomes the SEGMENT BODY: one function the runner
    can call again.  That is what makes the retry in lib/ot6.lua honest --
    a replayed attempt rebuilds every local, closure and step object the
    script has from source, rather than re-ticking step machinery that
    carries the failed attempt's counters.  The wrapper adds no scope the
    script can notice: its file-scope locals were already upvalues of the
    functions it defines, and nothing in the tree returns from file scope.

    Each half is wrapped in a function so its `return M` / `local M = ...`
    binds to the script's H.  The two-scope shape keeps each source file a
    valid Lua chunk on its own (no cross-file locals; the one core local the
    field half needs, seqStep, is exported on M).  The leading `;` is
    required: without it Lua reads `(function...` as a call on the previous
    line's value rather than a new statement.

    `raw_alias` prepends `local emu = __OT6_EMU_RAW or emu` inside each lib
    chunk: under the runtime write gate the global `emu` is a write-refusing
    proxy, and the lib keeps the raw handle while its own state-write
    waivers exist.  In an ungated compose __OT6_EMU_RAW is nil and the alias
    has no effect.

    Returns (composed_text, replaced); replaced False means the script never
    dofiles the lib (smoke.lua) and the text came through untouched.
    """
    alias = "local emu = __OT6_EMU_RAW or emu\n" if raw_alias else ""
    out, replaced = [], False
    for line in script.splitlines(keepends=True):
        if not replaced and "dofile(" in line and "lib/ot6.lua" in line:
            out.append("local H = (function()\n")
            out.append(alias)
            out.append(lib)
            out.append("\nend)()\n")
            for half in (field, contract):
                out.append(";(function(...)\n")
                out.append(alias)
                out.append(half)
                out.append("\nend)(H)\n")
            out.append(BODY_OPEN)
            replaced = True
        else:
            out.append(line)
    if replaced:
        out.append(BODY_CLOSE)
    return "".join(out), replaced


# Any .mss / .mss.lua string literal: group 1 = directory part (kept),
# group 2 = the basename the stack prefix goes onto.
_MSS_LIT = re.compile(r'"((?:[^"]*/)?)([A-Za-z0-9_]+\.mss(?:\.lua)?)"')

# Any H.sym("Name") / M.sym('Name') / sym("Name") reference: group 1 is the
# ca65 symbol reference to resolve out of ff6-en.dbg, either a bare name
# ("RandA") or a name qualified by the ca65 segment that defines it
# ("ExecCmd@battle_code"), which is how a caller disambiguates a name the
# linker emits more than once.  Matches only `sym(` at a word boundary, so
# `foo.symbolic(...)` is not a false positive.  Names found in comments are
# collected too, which is harmless because an extra OT6_SYMS entry is inert;
# see comment_only_refs(), which keeps the ambiguity check below from
# failing a compose over a name that only appears in prose.
_SYM_REF = re.compile(
    r'\bsym\s*\(\s*["\']([A-Za-z_][A-Za-z0-9_]*(?:@[A-Za-z0-9_.]+)?)["\']')


def comment_only_refs(script, refs):
    """Of `refs`, the subset whose every `sym("...")` occurrence is commented.
    Lua's `--` runs to end of line, so "is this match inside a comment?" is
    answered by whether `--` appears earlier on its own line.  (A `--` inside
    a string literal would fool this; the cost of being fooled is a warning
    instead of an error, never the reverse.)  This exists so the ambiguity
    check can be fatal for a real call while staying inert for prose.
    """
    live = set()
    for line in script.splitlines():
        cut = line.find("--")
        code = line if cut < 0 else line[:cut]
        live |= set(_SYM_REF.findall(code))
    return [r for r in refs if r not in live]


def parse_dbg_syms(dbg, wanted):
    """Resolve `wanted` ca65 symbol references against `dbg`.

    Returns (resolved, ambiguous):
      resolved   ref -> integer address, for refs that name exactly one place
      ambiguous  ref -> [(segment, address), ...] sorted, for refs that name
                 several places; the caller must disambiguate, and until it
                 does the ref is absent from `resolved`

    A ref is either a bare ca65 name ("RandA") or `Name@segment`
    ("ExecCmd@battle_code").  The .dbg carries one record per line; a
    `.proc`/label emits several with the same name (a `scope`, an `imp`
    import, and the `lab` definition), but only the `type=lab` record carries
    the `val=0x...` address, so only label lines are considered.

    ca65 scopes names per module, so a name can be defined in two modules
    and the linker records both.  Duplicate records that agree on the
    address are not ambiguous; only distinct addresses are.

    A name with no label record appears in neither dict, and H.sym() raises
    for it at runtime (the same failure as a missing savestate sidecar).  The
    same holds for an empty `wanted` or an absent .dbg (an unbuilt ROM).
    """
    if not wanted or not dbg.exists():
        return {}, {}
    wanted = list(dict.fromkeys(wanted))
    # ref -> (bare name, required segment or None)
    parts = {w: (w.split("@", 1) + [None])[:2] for w in wanted}
    bases = {b for b, _ in parts.values()}
    markers = {'name="%s"' % b: b for b in bases}
    val_re = re.compile(r"\bval=0x([0-9A-Fa-f]+)")
    seg_re = re.compile(r"\bseg=(\d+)")

    # One pass, collecting both kinds of record: base name -> {seg id ->
    # {addresses}}, plus the seg-id -> seg-name table needed to label them.
    # Segment names ("field_code", "battle_code") come from cfg/ff6-en.cfg and
    # survive the bank-layout shifts that move addresses, so a caller
    # disambiguates with a segment rather than an address.  This cannot exit
    # early, because "is this name unique?" can only be answered at end of
    # file.
    found, segs = {}, {}
    with dbg.open() as f:
        for line in f:
            if "type=lab" in line:
                for mk, base in markers.items():
                    if mk not in line:
                        continue
                    v, s = val_re.search(line), seg_re.search(line)
                    if v:
                        found.setdefault(base, {}).setdefault(
                            s.group(1) if s else "?", set()).add(
                                int(v.group(1), 16))
                    break
            elif line.startswith("seg\t"):
                i = re.search(r"\bid=(\d+)", line)
                n = re.search(r'\bname="([^"]*)"', line)
                if i and n:
                    segs[i.group(1)] = n.group(1)

    resolved, ambiguous = {}, {}
    for ref, (base, want_seg) in parts.items():
        by_seg = {segs.get(i, "seg" + i): v
                  for i, v in found.get(base, {}).items()}
        if want_seg is not None:
            by_seg = {s: v for s, v in by_seg.items() if s == want_seg}
        cands = sorted((s, a) for s, addrs in by_seg.items() for a in addrs)
        if len({a for _, a in cands}) == 1:
            resolved[ref] = cands[0][1]
        elif cands:
            ambiguous[ref] = cands
    return resolved, ambiguous


def stack_rewrite(script: str, prefix: str) -> str:
    """Prefix the basename of every .mss/.mss.lua literal in `script`.  Both
    directions must move together: prefixing only loadState references
    would boot gen_rapids from t2_scenario_hub and then let it overwrite the
    input-driven rapids_start/rapids_done with states generated from a
    contaminated boot.  Screenshot tags carry no .mss suffix and are
    untouched; comments mentioning state names are rewritten too, which is
    harmless.
    """
    if not prefix:
        return script
    if not re.fullmatch(r"[A-Za-z0-9_]+", prefix):
        raise ValueError(f"OT6_STACK={prefix!r}: prefix must be [A-Za-z0-9_]+")
    return _MSS_LIT.sub(lambda m: f'"{m.group(1)}{prefix}{m.group(2)}"', script)


def resolve_sidecar(ref, root):
    """Pick the sidecar file a "<path>.mss.lua" reference should embed.

    Every test writes tree-relative references ("build/states/x.mss.lua");
    an absolute reference is refused rather than resolved.  Composition is
    tree-local elsewhere as well: LIB ignores the script's literal dofile
    path the same way.

    Precedence, per reference:
      0. an absolute literal -> raise CrossTree, including one naming this
         tree, which would work only until the tree moves
      1. <root>/build/states/<basename>       -- wins if present
      2. the literal anchored at <root> (never the composer's cwd)
      3. the anchored literal escapes <root> (via ..) or crosses into a
         nested git tree inside <root> (an agent worktree under
         .claude/worktrees/ sits inside the main tree on disk but is a
         different checkout with a different ROM) -> raise CrossTree
      4. nowhere -> None; embed nothing, and the lib raises "sidecar not
         embedded" at loadState, which is a clear failure

    Rule 3's nested-.git check: a relative path can still be spelled through
    a nested checkout, and refusing it must not depend on how the reference
    was written.
    """
    literal = Path(ref)
    if literal.is_absolute():
        raise CrossTree(f"{ref} -- absolute sidecar reference; "
                        f"write it tree-relative (build/states/...)")
    local = root / "build" / "states" / literal.name
    if local.exists():
        return local
    literal = root / literal
    if literal.exists():
        resolved = literal.resolve()
        if not resolved.is_relative_to(root):
            raise CrossTree(ref)
        # Check whether the path, though inside root, crosses into a nested
        # checkout.  A git worktree (or submodule) marks its own top with a
        # .git entry, a file for worktrees and a directory for a clone, so
        # any .git between the literal and root means the file belongs to a
        # different tree.
        for parent in resolved.parents:
            if parent == root:
                break
            if (parent / ".git").exists():
                raise CrossTree(ref)
        return literal
    return None


def selftest() -> int:
    """Positive control for resolve_sidecar's precedence: `compose.py --selftest`.
    The bug this guards against is a wrong answer with no warning:
    composition that embeds another tree's savestate.  Each case below pins
    which file was chosen.
    """
    import tempfile

    ok = True

    def check(label, got, want):
        nonlocal ok
        if got != want:
            ok = False
            print(f"  FAIL {label}\n       got  {got}\n       want {want}")
        else:
            print(f"  pass {label}")

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp).resolve()
