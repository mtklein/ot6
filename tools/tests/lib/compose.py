#!/usr/bin/env python3
"""Compose a self-contained Lua test file for Mesen's testrunner: inlines the
test library (lib/ot6.lua, lib/ot6_field.lua, lib/ot6_contract.lua) and any
savestate sidecars a script references into one file that does no file
access at run time, since Mesen's default AllowIoOsAccess=false setting
makes runtime dofile()/loadfile() fail.

Transformations:
  1. `local H = dofile(".../lib/ot6.lua")` is replaced by the lib files;
     see inline_libs() for the shape.  Every script gets all three.
  2. For every `H.loadState("<path>.mss.lua")` reference whose sidecar file
     exists, the sidecar's base64 payload is embedded into a global table
     `OT6_STATES[basename]`; the lib's loadState() checks that table first.
     The sidecar is taken from this tree's build/states whenever it has
     one, and every embedded state is named, with a short hash, in a
     comment and a print() at the head of the composed file.

Usage:
    compose.py <script.lua> <out.lua>     # compose
    compose.py --digest <script.lua> <out>
        # the sha256 of the composed script's Lua token stream, plus the
        # environment the composition read; <out> is rewritten only when
        # that moved.  This is what a run depends on in the ninja graph
        # (savestate_ninja.py, configure.py), and what lib/stamps.py
        # recomputes to say whether a fixture is current.
    compose.py --sha <sidecar>            # a sidecar's short fingerprint
    compose.py --selftest

SCENARIO STACKING: `OT6_STACK=<prefix>` rewrites the basename of every
`.mss`/`.mss.lua` string literal in the script (never in the lib) at
compose time, so `OT6_STACK=t2_` composes gen_rapids into a script that
boots t2_scenario_hub.mss.lua and emits t2_rapids_*.mss.
"""
import hashlib
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE / "ot6.lua"            # battle core; yields the module table
FIELD = HERE / "ot6_field.lua"    # nav half; installs onto that same table
CONTRACT = HERE / "ot6_contract.lua"  # checkpoint entry/exit contracts
sys.path.insert(0, str(HERE))
import lua_fingerprint  # noqa: E402 -- what a .lua input's hash covers (#247)
ROOT = HERE.parent.parent.parent           # lib/ -> tests/ -> tools/ -> tree root
MARKER = "-- AUTOGENERATED by lib/compose.py; edit the source script instead."


def load_write_waivers(path):
    """The set of repo-relative paths carrying at least one state-write
    waiver.  Only the path column is read; the runtime gate is per script."""
    waived = set()
    if path.exists():
        for line in path.read_text().splitlines():
            if line.startswith("#") or not line.strip():
                continue
            waived.add(line.split("\t", 1)[0].strip())
    return waived


# The write-side emu surface, kept in sync with check_state_writes.py's
# TOKENS (the emu.* half; the .writeByte(/H.write/M.write wrapper tokens are
# lib entry points, which are removed with the lib's own waiver registry instead).
WRITE_GATE_SURFACE = [
    "write", "writeWord", "write16", "write32",
    "setState", "addCheat", "clearCheats",
    "rewind", "reset", "loadSavestate",
]


def write_gate_prologue():
    """The runtime half of the no-state-writes rule: runs before any user or
    lib code, captures the real `emu` in a file-local, then replaces the
    global with a proxy whose write surface raises an error.  Read-side
    calls pass through untouched.  Scripts whose file still carries
    state-write waivers compose without the prologue."""
    lines = [
        "-- RUNTIME WRITE GATE (issue #75): this script's file carries no\n",
        "-- state-write waivers, so the write-side emu surface is refused at\n",
        "-- runtime too. Snapshot helpers remain permitted (docs/TESTING.md).\n",
        "local __OT6_EMU_RAW = emu\n",
        "do\n",
        "  local proxy = setmetatable({}, { __index = __OT6_EMU_RAW })\n",
    ]
    for name in WRITE_GATE_SURFACE:
        lines.append(
            '  proxy.%s = function()\n'
            '    error("[ot6] runtime write gate (issue #75): emu.%s is '
            'forbidden here -- use snapshot helpers for complete restores; '
            'no selective gameplay edits (docs/TESTING.md)", 2)\n'
            '  end\n' % (name, name))
    lines += [
        "  emu = proxy\n",
        "end\n",
    ]
    return lines


def payload(sidecar: Path) -> str:
    """The base64 blob out of a `return "<b64>"` sidecar ("" if malformed)."""
    m = re.search(r'return\s+"([A-Za-z0-9+/=]+)"', sidecar.read_text())
    return m.group(1) if m else ""


def digest(b64: str) -> str:
    """Short fingerprint of an embedded payload, for the provenance lines.
    Hashes the base64 text rather than the sidecar file, so it can be
    recomputed from either side, a composed file or a sidecar."""
    return hashlib.sha256(b64.encode()).hexdigest()[:12]


class CrossTree(Exception):
    """A referenced sidecar exists only outside the composing tree."""


BODY_OPEN = ("H.segmentBody(function()  -- the segment body (lib/ot6.lua's "
             "retry runner replays this)\n")
BODY_CLOSE = "\nend)  -- H.segmentBody\n"


def inline_libs(script: str, lib: str, field: str, contract: str,
                raw_alias: bool = False):
    """Swap the script's `local H = dofile(".../lib/ot6.lua")` line for the
    lib halves, inlined:

        local H = (function()
        <lib/ot6.lua>              -- ends with `return M`
        end)()
        ;(function(...)
        <lib/ot6_field.lua>        -- first line `local M = ...` binds H
        end)(H)
        ;(function(...)
        <lib/ot6_contract.lua>     -- same shape: checkpoint contracts
        end)(H)
        H.segmentBody(function()
        <the rest of the script>
        end)

    The script's own text becomes the SEGMENT BODY: one function the runner
    can call again.  That is what makes the retry in lib/ot6.lua honest --
    a replayed attempt rebuilds every local, closure and step object the
    script has from source, rather than re-ticking step machinery that
    carries the failed attempt's counters.  The wrapper adds no scope the
    script can notice: its file-scope locals were already upvalues of the
    functions it defines, and nothing in the tree returns from file scope.

    Each half is wrapped in a function so its `return M` / `local M = ...`
    binds to the script's H.  The two-scope shape keeps each source file a
    valid Lua chunk on its own (no cross-file locals; the one core local the
    field half needs, seqStep, is exported on M).  The leading `;` is
    required: without it Lua reads `(function...` as a call on the previous
    line's value rather than a new statement.

    `raw_alias` prepends `local emu = __OT6_EMU_RAW or emu` inside each lib
    chunk: under the runtime write gate the global `emu` is a write-refusing
    proxy, and the lib keeps the raw handle while its own state-write
    waivers exist.  In an ungated compose __OT6_EMU_RAW is nil and the alias
    has no effect.

    Returns (composed_text, replaced); replaced False means the script never
    dofiles the lib (smoke.lua) and the text came through untouched.
    """
    alias = "local emu = __OT6_EMU_RAW or emu\n" if raw_alias else ""
    out, replaced = [], False
    for line in script.splitlines(keepends=True):
        if not replaced and "dofile(" in line and "lib/ot6.lua" in line:
            out.append("local H = (function()\n")
            out.append(alias)
            out.append(lib)
            out.append("\nend)()\n")
            for half in (field, contract):
                out.append(";(function(...)\n")
                out.append(alias)
                out.append(half)
                out.append("\nend)(H)\n")
            out.append(BODY_OPEN)
            replaced = True
        else:
            out.append(line)
    if replaced:
        out.append(BODY_CLOSE)
    return "".join(out), replaced


# Any .mss / .mss.lua string literal: group 1 = directory part (kept),
# group 2 = the basename the stack prefix goes onto.
_MSS_LIT = re.compile(r'"((?:[^"]*/)?)([A-Za-z0-9_]+\.mss(?:\.lua)?)"')

# Any H.sym("Name") / M.sym('Name') / sym("Name") reference: group 1 is the
# ca65 symbol reference to resolve out of ff6-en.dbg, either a bare name
# ("RandA") or a name qualified by the ca65 segment that defines it
# ("ExecCmd@battle_code"), which is how a caller disambiguates a name the
# linker emits more than once.  Matches only `sym(` at a word boundary, so
# `foo.symbolic(...)` is not a false positive.  Names found in comments are
# collected too, which is harmless because an extra OT6_SYMS entry is inert;
# see comment_only_refs(), which keeps the ambiguity check below from
# failing a compose over a name that only appears in prose.
_SYM_REF = re.compile(
    r'\bsym\s*\(\s*["\']([A-Za-z_][A-Za-z0-9_]*(?:@[A-Za-z0-9_.]+)?)["\']')


def comment_only_refs(script, refs):
    """Of `refs`, the subset whose every `sym("...")` occurrence is commented.
    Lua's `--` runs to end of line, so "is this match inside a comment?" is
    answered by whether `--` appears earlier on its own line.  (A `--` inside
    a string literal would fool this; the cost of being fooled is a warning
    instead of an error, never the reverse.)  This exists so the ambiguity
    check can be fatal for a real call while staying inert for prose.
    """
    live = set()
    for line in script.splitlines():
        cut = line.find("--")
        code = line if cut < 0 else line[:cut]
        live |= set(_SYM_REF.findall(code))
    return [r for r in refs if r not in live]


def parse_dbg_syms(dbg, wanted):
    """Resolve `wanted` ca65 symbol references against `dbg`.

    Returns (resolved, ambiguous):
      resolved   ref -> integer address, for refs that name exactly one place
      ambiguous  ref -> [(segment, address), ...] sorted, for refs that name
                 several places; the caller must disambiguate, and until it
                 does the ref is absent from `resolved`

    A ref is either a bare ca65 name ("RandA") or `Name@segment`
    ("ExecCmd@battle_code").  The .dbg carries one record per line; a
    `.proc`/label emits several with the same name (a `scope`, an `imp`
    import, and the `lab` definition), but only the `type=lab` record carries
    the `val=0x...` address, so only label lines are considered.

    ca65 scopes names per module, so a name can be defined in two modules
    and the linker records both.  Duplicate records that agree on the
    address are not ambiguous; only distinct addresses are.

    A name with no label record appears in neither dict, and H.sym() raises
    for it at runtime (the same failure as a missing savestate sidecar).  The
    same holds for an empty `wanted` or an absent .dbg (an unbuilt ROM).
    """
    if not wanted or not dbg.exists():
        return {}, {}
    wanted = list(dict.fromkeys(wanted))
    # ref -> (bare name, required segment or None)
    parts = {w: (w.split("@", 1) + [None])[:2] for w in wanted}
    bases = {b for b, _ in parts.values()}
    markers = {'name="%s"' % b: b for b in bases}
    val_re = re.compile(r"\bval=0x([0-9A-Fa-f]+)")
    seg_re = re.compile(r"\bseg=(\d+)")

    # One pass, collecting both kinds of record: base name -> {seg id ->
    # {addresses}}, plus the seg-id -> seg-name table needed to label them.
    # Segment names ("field_code", "battle_code") come from cfg/ff6-en.cfg and
    # survive the bank-layout shifts that move addresses, so a caller
    # disambiguates with a segment rather than an address.  This cannot exit
    # early, because "is this name unique?" can only be answered at end of
    # file.
    found, segs = {}, {}
    with dbg.open() as f:
        for line in f:
            if "type=lab" in line:
                for mk, base in markers.items():
                    if mk not in line:
                        continue
                    v, s = val_re.search(line), seg_re.search(line)
                    if v:
                        found.setdefault(base, {}).setdefault(
                            s.group(1) if s else "?", set()).add(
                                int(v.group(1), 16))
                    break
            elif line.startswith("seg\t"):
                i = re.search(r"\bid=(\d+)", line)
                n = re.search(r'\bname="([^"]*)"', line)
                if i and n:
                    segs[i.group(1)] = n.group(1)

    resolved, ambiguous = {}, {}
    for ref, (base, want_seg) in parts.items():
        by_seg = {segs.get(i, "seg" + i): v
                  for i, v in found.get(base, {}).items()}
        if want_seg is not None:
            by_seg = {s: v for s, v in by_seg.items() if s == want_seg}
        cands = sorted((s, a) for s, addrs in by_seg.items() for a in addrs)
        if len({a for _, a in cands}) == 1:
            resolved[ref] = cands[0][1]
        elif cands:
            ambiguous[ref] = cands
    return resolved, ambiguous


def stack_rewrite(script: str, prefix: str) -> str:
    """Prefix the basename of every .mss/.mss.lua literal in `script`.  Both
    directions must move together: prefixing only loadState references
    would boot gen_rapids from t2_scenario_hub and then let it overwrite the
    input-driven rapids_start/rapids_done with states generated from a
    contaminated boot.  Screenshot tags carry no .mss suffix and are
    untouched; comments mentioning state names are rewritten too, which is
    harmless.
    """
    if not prefix:
        return script
    if not re.fullmatch(r"[A-Za-z0-9_]+", prefix):
        raise ValueError(f"OT6_STACK={prefix!r}: prefix must be [A-Za-z0-9_]+")
    return _MSS_LIT.sub(lambda m: f'"{m.group(1)}{prefix}{m.group(2)}"', script)


def resolve_sidecar(ref, root):
    """Pick the sidecar file a "<path>.mss.lua" reference should embed.

    Every test writes tree-relative references ("build/states/x.mss.lua");
    an absolute reference is refused rather than resolved.  Composition is
    tree-local elsewhere as well: LIB ignores the script's literal dofile
    path the same way.

    Precedence, per reference:
      0. an absolute literal -> raise CrossTree, including one naming this
         tree, which would work only until the tree moves
      1. <root>/build/states/<basename>       -- wins if present
      2. the literal anchored at <root> (never the composer's cwd)
      3. the anchored literal escapes <root> (via ..) or crosses into a
         nested git tree inside <root> (an agent worktree under
         .claude/worktrees/ sits inside the main tree on disk but is a
         different checkout with a different ROM) -> raise CrossTree
      4. nowhere -> None; embed nothing, and the lib raises "sidecar not
         embedded" at loadState, which is a clear failure

    Rule 3's nested-.git check: a relative path can still be spelled through
    a nested checkout, and refusing it must not depend on how the reference
    was written.
    """
    literal = Path(ref)
    if literal.is_absolute():
        raise CrossTree(f"{ref} -- absolute sidecar reference; "
                        f"write it tree-relative (build/states/...)")
    local = root / "build" / "states" / literal.name
    if local.exists():
        return local
    literal = root / literal
    if literal.exists():
        resolved = literal.resolve()
        if not resolved.is_relative_to(root):
            raise CrossTree(ref)
        # Check whether the path, though inside root, crosses into a nested
        # checkout.  A git worktree (or submodule) marks its own top with a
        # .git entry, a file for worktrees and a directory for a clone, so
        # any .git between the literal and root means the file belongs to a
        # different tree.
        for parent in resolved.parents:
            if parent == root:
                break
            if (parent / ".git").exists():
                raise CrossTree(ref)
        return literal
    return None


def selftest() -> int:
    """Positive control for resolve_sidecar's precedence: `compose.py --selftest`.
    The bug this guards against is a wrong answer with no warning:
    composition that embeds another tree's savestate.  Each case below pins
    which file was chosen.
    """
    import tempfile

    ok = True

    def check(label, got, want):
        nonlocal ok
        if got != want:
            ok = False
            print(f"  FAIL {label}\n       got  {got}\n       want {want}")
        else:
            print(f"  pass {label}")

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp).resolve()
        main_tree, work = tmp / "ot6", tmp / "ot6" / ".claude" / "wt" / "a"
        for t in (main_tree, work):
            (t / "build" / "states").mkdir(parents=True)
        # A worktree nests inside the main tree on disk, as real ones do, so
        # "outside this tree" cannot be a reversed prefix test.
        m_state = main_tree / "build" / "states" / "s.mss.lua"
        w_state = work / "build" / "states" / "s.mss.lua"
        m_state.write_text('return "TUFJTg=="\n')
        w_state.write_text('return "V09SSw=="\n')

        def refused(label, ref, tree):
            try:
                got = resolve_sidecar(ref, tree)
                check(label, f"returned {got}", "CrossTree")
            except CrossTree:
                check(label, "CrossTree", "CrossTree")

        # 0. Rule 0: an absolute reference is refused no matter whose tree
        # it names, including the composing tree's own path.
        refused("absolute ref refused even naming the composing tree",
                str(w_state), work)
        refused("absolute ref into another tree refused", str(m_state), work)
        # 1. This tree's build/states wins on basename, wherever the
        # relative literal points.
        check("local basename copy beats the literal's location",
              resolve_sidecar("fixtures/s.mss.lua", work), w_state)
        # 2. A relative literal anchors at the composing tree's root, never
        # the composer's cwd.
        odd = work / "fixtures"
        odd.mkdir()
        (odd / "x.mss.lua").write_text('return "WA=="\n')
        check("relative literal resolves against the tree root",
              resolve_sidecar("fixtures/x.mss.lua", work), odd / "x.mss.lua")
        # 3a. Escaping the tree via .. is refused, not resolved.
        (tmp / "outside.mss.lua").write_text('return "T1VU"\n')
        refused("dot-dot escape refused", "../../../../outside.mss.lua", work)
        # 3b. A reference spelled through a nested worktree stays inside root
        # but names a different checkout generated from a different ROM.
        # (A worktree's top carries .git as a file; model that.)
        nested = main_tree / ".claude" / "worktrees" / "agent-b"
        (nested / "build" / "states").mkdir(parents=True)
        (nested / ".git").write_text("gitdir: /somewhere/else\n")
        n_state = nested / "build" / "states" / "nested_only.mss.lua"
        n_state.write_text('return "TkVTVA=="\n')
        refused("nested-worktree reference refused",
                ".claude/worktrees/agent-b/build/states/nested_only.mss.lua",
                main_tree)
        # 4. Missing everywhere -> None (the lib raises at loadState).
        check("absent everywhere yields None",
              resolve_sidecar("build/states/nope.mss.lua", work), None)

    # -- stack_rewrite: both directions of a route must move together --
    src = ('local HUB = "/Users/x/ot6/build/states/scenario_hub.mss.lua"\n'
           'H.saveState("rapids_done.mss")\n'
           'H.screenshot("rapids_battle1")\n')
    got = stack_rewrite(src, "t2_")
    check("stack prefixes the boot sidecar reference",
          '"/Users/x/ot6/build/states/t2_scenario_hub.mss.lua"' in got, True)
    check("stack prefixes the emitted state name",
          'H.saveState("t2_rapids_done.mss")' in got, True)
    check("stack leaves screenshot tags alone",
          'H.screenshot("rapids_battle1")' in got, True)
    check("empty prefix is the identity", stack_rewrite(src, ""), src)
    try:
        stack_rewrite(src, "bad/../prefix")
        check("stack refuses a non-word prefix", "no raise", "ValueError")
    except ValueError:
        check("stack refuses a non-word prefix", "ValueError", "ValueError")

    # -- inline_libs: all three halves are inlined, field and contract fed H --
    lib_src = "-- core\nlocal M = {}\nCOREBODY\nreturn M"
    field_src = "-- field\nlocal M = ...\nFIELDBODY"
    contract_src = "-- contract\nlocal M = ...\nCONTRACTBODY"
    script_src = ("-- a test\n"
                  'local H = dofile("/Users/x/ot6/tools/tests/lib/ot6.lua")\n'
                  "H.run({}, {})\n")
    got, replaced = inline_libs(script_src, lib_src, field_src, contract_src)
    check("inline replaces the dofile line", replaced, True)
    check("inline drops the dofile call itself", "dofile(" not in got, True)
    check("inline binds the core to H", "local H = (function()" in got, True)
    check("inline appends the field half after the core",
          -1 < got.find("COREBODY") < got.find("FIELDBODY"), True)
    check("inline appends the contract half after the field half (#25)",
          -1 < got.find("FIELDBODY") < got.find("CONTRACTBODY"), True)
    check("inline starts the field chunk as a new statement (the ';')",
          ";(function(...)" in got, True)
    check("inline hands BOTH trailing chunks H", got.count("end)(H)"), 2)
    check("inline leaves the script's own text intact, inside the body",
          got.startswith("-- a test\n") and "H.run({}, {})\n" in got, True)
    check("inline wraps the script in the replayable segment body (#178)",
          "H.segmentBody(function()" in got
          and got.rstrip().endswith("end)  -- H.segmentBody"), True)
    check("inline opens the body AFTER the three lib halves",
          got.find("CONTRACTBODY") < got.find("H.segmentBody(function()"),
          True)
    got2, replaced2 = inline_libs("print('no lib')\n", lib_src, field_src,
                                  contract_src)
    check("no lib reference -> untouched, unreplaced",
          (got2, replaced2), ("print('no lib')\n", False))

    # -- the runtime write gate: prologue shape, lib alias, and the
    #    waiver-list decision that arms it per script -----------------------
    alias_line = "local emu = __OT6_EMU_RAW or emu\n"
    check("default inline carries NO raw-emu alias (strict once lib is clean)",
          alias_line in got, False)
    got3, _ = inline_libs(script_src, lib_src, field_src, contract_src,
                          raw_alias=True)
    check("raw_alias plants the alias in all THREE lib chunks",
          got3.count(alias_line), 3)
    check("raw_alias keeps the alias OUT of user code (only after wrappers)",
          all(prev.rstrip().endswith(("(function()", "(function(...)"))
              for prev, line in zip(got3.splitlines(True),
                                    got3.splitlines(True)[1:])
              if line == alias_line), True)
    gate = "".join(write_gate_prologue())
    for name in WRITE_GATE_SURFACE:
        check(f"gate refuses emu.{name}", f"proxy.{name} = function()" in gate,
              True)
    check("gate captures the raw handle before proxying",
          gate.find("local __OT6_EMU_RAW = emu")
          < gate.find("emu = proxy") > -1, True)
    check("gate reads everything through the raw handle (__index passthrough)",
          "{ __index = __OT6_EMU_RAW }" in gate, True)
    with tempfile.TemporaryDirectory() as tmp:
        w = Path(tmp) / "waivers.txt"
        w.write_text("# comment line\n"
                     "\n"
                     "tools/tests/old_cheater.lua\temu.write\n"
                     "tools/tests/old_cheater.lua\t.writeByte(\n"
                     "tools/tests/lib/ot6_field.lua\temu.write\n")
        waived = load_write_waivers(w)
        check("waiver load: one path per waived file, comments skipped",
              waived, {"tools/tests/old_cheater.lua",
                       "tools/tests/lib/ot6_field.lua"})
        check("waiver load: a missing list waives nothing (everything gated)",
              load_write_waivers(Path(tmp) / "absent.txt"), set())
    # the assumptions the wrapper makes about the real lib files:
    check("lib/ot6.lua ends by returning its module table",
          LIB.read_text().rstrip().endswith("return M"), True)
    check("lib/ot6_field.lua opens by receiving that table (local M = ...)",
          any(l.strip() == "local M = ..."
              for l in FIELD.read_text().splitlines()[:40]), True)
    check("lib/ot6_contract.lua opens by receiving that table (local M = ...)",
          any(l.strip() == "local M = ..."
              for l in CONTRACT.read_text().splitlines()[:60]), True)

    # -- _SYM_REF: collect H.sym/M.sym names, ignore look-alikes and dupes --
    refs = _SYM_REF.findall(
        'local R = H.sym("RandA")\n'
        "local S = M.sym('Ot6ShieldTbl')\n"
        'local R2 = H.sym("RandA")\n'          # a repeat: dedup is the caller's
        '-- a name in a comment: sym("InComment")\n'
        'local Q = H.sym("ExecCmd@battle_code")\n'
        'foo.symbolic("NotASym"); local t = symtab["NotASym"]\n')
    check("sym refs collect real calls (with the comment name, harmlessly)",
          refs, ["RandA", "Ot6ShieldTbl", "RandA", "InComment",
                 "ExecCmd@battle_code"])
    check("sym refs ignore symbolic()/symtab[] look-alikes",
          "NotASym" not in refs, True)

    # -- comment_only_refs: what makes the ambiguity check fatal for a call
    #    and inert for prose.  Both halves matter: a doc comment naming a
    #    duplicated symbol must not fail a build (probe_dottick.lua's header
    #    does that), and a real call must not be excused by an unrelated
    #    comment elsewhere in the file that names it.
    src = ('-- doc: H.sym("OnlyInProse") is the hazard\n'
           'local A = H.sym("Called")\n'
           '-- and H.sym("Called") is discussed here too\n'
           'local B = H.sym("Tail")  -- trailing comment after real code\n')
    got = comment_only_refs(src, ["OnlyInProse", "Called", "Tail", "Absent"])
    check("comment-only ref is reported inert", "OnlyInProse" in got, True)
    check("a called name is NOT excused by a comment that also names it",
          "Called" in got, False)
    check("a call with a trailing comment on the same line still counts",
          "Tail" in got, False)
    check("a ref that appears nowhere counts as inert (nothing calls it)",
          "Absent" in got, True)

    # -- parse_dbg_syms: the type=lab record's val wins; scope/imp are skipped;
    #    an unknown name is absent (H.sym raises for it at runtime); and a
    #    duplicated name is ambiguous rather than resolving to the first --
    with tempfile.TemporaryDirectory() as tmp:
        dbg = Path(tmp) / "ff6-en.dbg"
        dbg.write_text(
            'seg\tid=6,name="field_code",start=0xC00000,size=0xD61F\n'
            'seg\tid=52,name="battle_code",start=0xC20000,size=0x6523\n'
            'seg\tid=67,name="ot6_data",start=0xF00000,size=0x1000\n'
            'scope\tid=1,name="RandA",mod=2,type=scope,size=4\n'
            'sym\tid=2,name="RandA",addrsize=absolute,def=9,type=imp,exp=2\n'
            'sym\tid=3,name="RandA",scope=1700,def=9,val=0xC24B98,seg=52,type=lab\n'
            'sym\tid=4,name="Ot6ShieldTbl",scope=1700,val=0xF01050,seg=67,type=lab\n'
            'sym\tid=5,name="Decoy",scope=0,val=0xDEAD00,seg=1,type=equ\n'
            # One name, two modules, two addresses.
            'sym\tid=6,name="ExecCmd",scope=228,val=0xC09B1B,seg=6,type=lab\n'
            'sym\tid=7,name="ExecCmd",scope=1700,val=0xC213EA,seg=52,type=lab\n'
            # A name recorded twice at the same address is not ambiguous;
            # only different addresses are.
            'sym\tid=8,name="Twice",scope=1700,val=0xC22000,seg=52,type=lab\n'
            'sym\tid=9,name="Twice",scope=1701,val=0xC22000,seg=52,type=lab\n')
        got, amb = parse_dbg_syms(
            dbg, ["RandA", "Ot6ShieldTbl", "Missing", "Decoy", "Twice",
                  "ExecCmd", "ExecCmd@battle_code", "ExecCmd@field_code",
                  "ExecCmd@no_such_seg"])
        check("parse picks the type=lab val over scope/imp",
              got.get("RandA"), 0xC24B98)
        check("parse resolves a second wanted label",
              got.get("Ot6ShieldTbl"), 0xF01050)
        check("parse omits an unknown name", "Missing" in got, False)
        check("parse omits a non-lab (type=equ) record", "Decoy" in got, False)
        check("a duplicated name at ONE address resolves (not ambiguous)",
              (got.get("Twice"), "Twice" in amb), (0xC22000, False))
        check("a name at TWO addresses does NOT resolve", "ExecCmd" in got,
              False)
        check("...it is reported ambiguous, with both segments and addresses",
              amb.get("ExecCmd"),
              [("battle_code", 0xC213EA), ("field_code", 0xC09B1B)])
        check("@segment picks the battle one", got.get("ExecCmd@battle_code"),
              0xC213EA)
        check("@segment picks the field one", got.get("ExecCmd@field_code"),
              0xC09B1B)
        check("@segment that matches nothing resolves to nothing",
              ("ExecCmd@no_such_seg" in got, "ExecCmd@no_such_seg" in amb),
              (False, False))
        check("parse of an absent .dbg is empty (defers to H.sym)",
              parse_dbg_syms(Path(tmp) / "nope.dbg", ["RandA"]), ({}, {}))
        check("parse of no wanted names is empty (inert injection)",
              parse_dbg_syms(dbg, []), ({}, {}))

    # -- ot6.lua's accessor must know about the ambiguity table compose emits;
    #    otherwise a comment-only duplicate would fall through to the plain
    #    "not in ff6-en.dbg" message, which tells the reader to rebuild.
    check("lib/ot6.lua M.sym consults OT6_SYMS_AMBIG",
          "OT6_SYMS_AMBIG" in LIB.read_text(), True)


    # -- compose_script / composed_digest: the digest a run's dependency is.
    #    A comment or a re-indent anywhere in what is inlined leaves it alone;
    #    a code edit in the lib, an embedded sidecar, the write gate and the
    #    environment the composition reads each move it.
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        lib = root / "tools" / "tests" / "lib"
        lib.mkdir(parents=True)
        (root / "build" / "states").mkdir(parents=True)
        (root / "tools" / "tests" / "gen_x.lua").write_text(
            'local H = dofile("tools/tests/lib/ot6.lua")\n'
            'H.run({}, { H.loadState("build/states/a.mss.lua") })\n')
        (lib / "ot6.lua").write_text("local M = {}\nM.v = 1\nreturn M\n")
        (lib / "ot6_field.lua").write_text("local M = ...\nM.f = 1\n")
        (lib / "ot6_contract.lua").write_text("local M = ...\nM.c = 1\n")
        (root / "build" / "states" / "a.mss.lua").write_text('return "QUFB"\n')
        gen = root / "tools" / "tests" / "gen_x.lua"

        def dig(env=None):
            return composed_digest(compose_script(gen, root, env or {})[0])
        base = dig()
        check("a script composes to a 64-hex digest",
              bool(re.fullmatch(r"[0-9a-f]{64}", base)), True)
        check("composing twice gives the same digest", dig(), base)
        (lib / "ot6.lua").write_text(
            "-- a comment\nlocal M = {}\n\n  M.v = 1   -- why\nreturn M\n")
        check("a lib comment and whitespace edit leaves the digest", dig(), base)
        (lib / "ot6.lua").write_text("local M = {}\nM.v = 2\nreturn M\n")
        moved = dig()
        check("MUTANT a lib code edit moves the digest", moved != base, True)
        (lib / "ot6.lua").write_text("local M = {}\nM.v = 1\nreturn M\n")
        (root / "build" / "states" / "a.mss.lua").write_text('return "QUJD"\n')
        check("MUTANT a regenerated embedded state moves the digest",
              dig() != base, True)
        (root / "build" / "states" / "a.mss.lua").write_text('return "QUFB"\n')
        check("MUTANT the checkpoint a run Continues moves the digest",
              dig({"OT6_SRAM_CHECKPOINT": "build/checkpoints/k-v1"}) != base,
              True)
        (root / "tools").mkdir(exist_ok=True)
        (root / "tools" / "state_write_waivers.txt").write_text(
            "tools/tests/gen_other.lua\temu.write\n")
        check("another script's waiver leaves this digest", dig(), base)
        (root / "tools" / "state_write_waivers.txt").write_text(
            "tools/tests/gen_x.lua\temu.write\n")
        check("MUTANT this script's own waiver (the write gate off) moves it",
              dig() != base, True)
        (root / "tools" / "state_write_waivers.txt").write_text("")
        check("the composed text names the embedded state tree-relative",
              "<- build/states/a.mss.lua" in compose_script(gen, root, {})[0],
              True)
        (root / "VERSION").write_text("1.0\n")
        ver = root / "tools" / "tests" / "title_x.lua"
        ver.write_text('local H = dofile("tools/tests/lib/ot6.lua")\n'
                       'H.run({}, { H.call(function() return OT6_VERSION end) })\n')
        v1 = composed_digest(compose_script(ver, root, {})[0])
        check("a script that names OT6_VERSION gets the tree's VERSION",
              'OT6_VERSION = "1.0"' in compose_script(ver, root, {})[0], True)
        (root / "VERSION").write_text("1.1\n")
        check("MUTANT a VERSION bump moves the digest of a script that "
              "names OT6_VERSION",
              composed_digest(compose_script(ver, root, {})[0]) != v1, True)
        check("...and no other script's", dig(), base)
        out = root / "d.digest"
        main_digest(gen, out, root, {})
        m1 = out.stat().st_mtime_ns
        os.utime(out, ns=(m1 - 10**9, m1 - 10**9))
        main_digest(gen, out, root, {})
        check("--digest leaves an unmoved digest file alone (restat)",
              out.stat().st_mtime_ns, m1 - 10**9)
        check("--digest records the environment the composition read",
              out.read_text().splitlines()[1:], [])
        main_digest(gen, out, root, {"OT6_SRAM_CHECKPOINT": "build/checkpoints/k"})
        check("...and an environment it read",
              out.read_text().splitlines()[1:],
              ["env OT6_SRAM_CHECKPOINT=build/checkpoints/k"])

    print("selftest: " + ("ok" if ok else "FAILED"))
    return 0 if ok else 1


class ComposeError(Exception):
    """A script that cannot be composed; the message says why."""


# The environment composition reads: the runner's knobs and the checkpoint a
# run Continues.  --digest records the ones set, so the stamp checker
# (lib/stamps.py) composes again exactly as the run did.
COMPOSE_ENV = ("OT6_STACK", "OT6_ACTION_TRACE", "OT6_RETRIES",
               "OT6_SEED_SHIFT", "OT6_SHIFT_PROBE", "OT6_WATCHDOG",
               "OT6_COVERAGE", "OT6_SRAM_CHECKPOINT", "OT6_DBG")


def compose_script(script_path, root=ROOT, env=None):
    """The composed text of `script_path` in tree `root` under `env` (the
    process environment by default), and the warnings composing it raised.
    Raises ComposeError for a script that cannot be composed."""
    env = os.environ if env is None else env
    root = Path(root)
    script_path = Path(script_path)
    libdir = root / "tools" / "tests" / "lib"
    notes = []
    script = script_path.read_text()
    lib = (libdir / "ot6.lua").read_text()
    field = (libdir / "ot6_field.lua").read_text()
    contract = (libdir / "ot6_contract.lua").read_text()

    # Composing is not idempotent (the usage-example dofile line in the
    # inlined lib header would re-trigger inlining), so re-composition is
    # refused.
    if script.startswith(MARKER):
        raise ComposeError(f"{script_path} is already composed; refusing to "
                           f"re-compose")

    # Scenario stacking: rewrite state basenames before sidecar collection,
    # so the resolver sees (and embeds) the prefixed names.  The script is
    # rewritten and the lib is not: the lib's own .mss mentions are
    # documentation.
    stack = env.get("OT6_STACK", "")
    if stack:
        script = stack_rewrite(script, stack)
        notes.append(f"stack prefix {stack!r} applied to {script_path}")

    # Collect referenced savestate sidecars: any "<path>.mss.lua" string
    # literal in the script.  resolve_sidecar() owns the precedence.
    states, sources = {}, {}
    for ref in dict.fromkeys(re.findall(r'"([^"]+\.mss\.lua)"', script)):
        try:
            p = resolve_sidecar(ref, root)
        except CrossTree as why:
            raise ComposeError(
                f"{script_path} references {ref} [{why}], which exists only "
                f"OUTSIDE this tree ({root}).  Refusing to compose another "
                f"tree's savestate: it was generated from a different ROM, so "
                f"a run against it proves nothing.  Generate it here (ninja "
                f"build/states/<state>.mss.lua), or seed this tree with "
                f"tools/worktree-setup.sh.")
        if p is None:
            continue
        b64 = payload(p)
        if b64:
            name = Path(ref).name
            states[name] = b64
            sources[name] = p.relative_to(root) if p.is_relative_to(root) else p

    # The runtime write gate.  Armed per script by the same waiver registry
    # the static checker enforces: a file with no waivers is declared not to
    # write, and the prologue enforces that at runtime too.  A script from
    # outside the tree (a scratch probe) has no waivers by construction and
    # is always gated.
    waived_files = load_write_waivers(root / "tools" / "state_write_waivers.txt")
    try:
        rel = str(script_path.resolve().relative_to(root.resolve())).replace(os.sep, "/")
    except ValueError:
        rel = script_path.name
    gated = rel not in waived_files
    lib_alias = any(w.startswith("tools/tests/lib/") for w in waived_files)

    preamble = [MARKER + "\n"]
    if env.get("OT6_ACTION_TRACE") == "1":
        preamble.append("OT6_ACTION_TRACE = true\n")
    # The segment runner's knobs (lib/ot6.lua).  Mesen's Lua cannot read the
    # environment, so they ride the preamble like OT6_SYMS does:
    #   OT6_SCRIPT      which script this is; `gen_*` means a segment, which
    #                   is what turns retries and the watchdogs on by default
    #   OT6_RETRIES     attempts allowed, overriding the default and the
    #                   script's own opts.retries (seed_sweep.py sets 1)
    #   OT6_SEED_SHIFT  idle frames at the boot point before the body walks
    #                   on: the sweep's per-seed offset
    #   OT6_WATCHDOG    1/0 to force the fast-failure watchdogs on or off
    #   OT6_SHIFT_PROBE stride: run the body to its first battle once per
    #                   shift across one 60-frame period and log each first
    #                   battle's RNG key (#208; seed_sweep.py --probe)
    preamble.append('OT6_SCRIPT = "%s"\n' % script_path.stem)
    # The tree's VERSION file, for a script that checks the version the ROM
    # shows against the one the tree says (menu_configversion): Mesen's
    # sandbox cannot read files.  Only a script that names OT6_VERSION gets
    # it, so a VERSION bump moves no other script's composed program.
    if re.search(r"\bOT6_VERSION\b", script):
        version = (root / "VERSION").read_text().strip()
        preamble.append('OT6_VERSION = "%s"\n'
                        % version.replace("\\", "\\\\").replace('"', '\\"'))
    for var in ("OT6_RETRIES", "OT6_SEED_SHIFT", "OT6_SHIFT_PROBE",
                "OT6_WATCHDOG"):
        raw = env.get(var)
        if raw is None or raw == "":
            continue
        try:
            preamble.append("%s = %d\n" % (var, int(raw)))
        except ValueError:
            raise ComposeError(f"{var}={raw!r} is not an integer")
    # Coverage flag: Mesen's Lua sandbox blocks os.getenv, so it rides the
    # preamble too, set only when OT6_COVERAGE is in this compose's
    # environment, so lib/ot6.lua's coverageFlush stays a no-op otherwise.
    if env.get("OT6_COVERAGE"):
        preamble.append("OT6_COVERAGE = true  -- lib/ot6.lua coverageFlush (#130)\n")
    # The SRAM checkpoint run.sh installs for this run, if any (#217).  A
    # script that boots differently depending on whether it was handed a
    # checkpoint cannot read the environment (os.getenv is nil under Mesen's
    # sandbox), so it is passed as a preamble global, its value the
    # checkpoint directory exactly as it appeared in the environment.
    ck = env.get("OT6_SRAM_CHECKPOINT")
    if ck:
        preamble.append('OT6_SRAM_CHECKPOINT = %s  -- the checkpoint run.sh '
                        'installed (#217)\n'
                        % ('"%s"' % ck.replace("\\", "\\\\").replace('"', '\\"')))
    if gated:
        preamble += write_gate_prologue()
    else:
        preamble.append(f"-- runtime write gate OFF: {rel} still carries "
                        f"state-write waivers (registry; "
                        f"tools/state_write_waivers.txt)\n")
    # Record which sidecar was embedded, in the composed file itself: a
    # state mismatch otherwise looks like a ROM bug, with nothing naming
    # the file it came from.  The print() lands in the run log and the
    # comment stays in the composed artifact.
    if states:
        for name, b64 in states.items():
            preamble.append(f"-- state {name} sha={digest(b64)} "
                            f"({len(b64)} b64 chars) <- {sources[name]}\n")
        preamble.append("OT6_STATES = {\n")
        for name, b64 in states.items():
            preamble.append(f'  ["{name}"] = "{b64}",\n')
        preamble.append("}\n")
        for name, b64 in states.items():
            preamble.append(f'print("[ot6] state {name} sha={digest(b64)} '
                            f'<- {sources[name]}")\n')

    # OT6 symbol addresses, derived from this tree's ff6-en.dbg the same way
    # OT6_STATES embeds sidecars.  Only symbols named via H.sym("...") are
    # collected.  The scan covers the libs as well as the test, because the
    # libs are inlined into every composed script and so can call H.sym
    # exactly as a test can; an unused entry costs one table row.
    dbg = Path(env.get("OT6_DBG") or (root / "ff6" / "rom" / "ff6-en.dbg"))
    sym_text = "\n".join([script, lib, field, contract])
    sym_names = list(dict.fromkeys(_SYM_REF.findall(sym_text)))
    if sym_names:
        syms, ambig = parse_dbg_syms(dbg, sym_names)
        preamble.append("-- OT6 symbols from ff6-en.dbg (via lib/compose.py)\n")
        preamble.append("OT6_SYMS = {\n")
        for name in sym_names:
            if name in syms:
                preamble.append(f'  ["{name}"] = 0x{syms[name]:06X},\n')
        preamble.append("}\n")
        # A named-but-unresolved symbol is a non-fatal warning here; the
        # failure comes from H.sym raising at runtime (an unbuilt ROM, or a
        # mistyped name).
        for name in sym_names:
            if name not in syms and name not in ambig:
                msg = (f"symbol {name} not found in ff6/rom/ff6-en.dbg "
                       f"-- rebuild the ROM, or check the name")
                preamble.append(f'print("[ot6] WARNING: {msg}")\n')
                notes.append(f"WARNING: {msg}")
        # An ambiguous name is fatal rather than deferred, except a name
        # whose every occurrence is inside a comment (the ref collector
        # over-collects from prose; probe_dottick.lua's header spells out
        # `H.sym("ExecCmd")`): that is recorded in OT6_SYMS_AMBIG instead,
        # and H.sym raises the same message if the name is called.
        if ambig:
            inert = set(comment_only_refs(sym_text, ambig))
            live = []
            for name, cands in sorted(ambig.items()):
                where = ", ".join(f"{s}=0x{a:06X}" for s, a in cands)
                msg = (f"symbol {name} is AMBIGUOUS in ff6/rom/ff6-en.dbg "
                       f"({where}) -- name the segment you mean, e.g. "
                       f'H.sym("{name.split("@")[0]}@{cands[0][0]}")')
                if name in inert:
                    preamble.append(f'  -- ambiguous: {msg}\n')
                else:
                    live.append(f"{script_path}: {msg}")
            if live:
                raise ComposeError("\n".join(live))
            preamble.append("OT6_SYMS_AMBIG = {\n")
            for name, cands in sorted(ambig.items()):
                where = ", ".join(f"{s}=0x{a:06X}" for s, a in cands)
                preamble.append(f'  ["{name}"] = "{where}",\n')
            preamble.append("}\n")

    composed, replaced = inline_libs(script, lib, field, contract,
                                     raw_alias=lib_alias)
    if not replaced:
        # the script doesn't use the lib (e.g. smoke.lua): passed through,
        # marked
        return MARKER + "\n" + script, notes + ["no lib reference; copied as-is"]
    return "".join(preamble) + composed, notes


def composed_digest(text):
    """sha256 of a composed script's Lua token stream
    (lua_fingerprint.tokens: comments and whitespace dropped, strings
    kept): what a run's composition dependency is."""
    toks = lua_fingerprint.tokens(text)
    return hashlib.sha256(("\n".join(toks) + "\n").encode("utf-8",
                                                          "surrogateescape")).hexdigest()


def digest_record(text, env):
    """The --digest file's text: the digest, then one `env K=V` line per
    variable of COMPOSE_ENV the composition read."""
    lines = [composed_digest(text)]
    lines += [f"env {k}={env[k]}" for k in COMPOSE_ENV if env.get(k)]
    return "\n".join(lines) + "\n"


def main_digest(script_path, out, root=ROOT, env=None):
    """--digest: write the record, only when it changed (ninja restat)."""
    env = os.environ if env is None else env
    text, _ = compose_script(script_path, root, env)
    rec = digest_record(text, env)
    out = Path(out)
    if not (out.exists() and out.read_text() == rec):
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_name(out.name + ".tmp")
        tmp.write_text(rec)
        os.replace(tmp, out)
    return 0


def main() -> int:
    argv = sys.argv[1:]
    if argv == ["--selftest"]:
        return selftest()
    # --sha <sidecar>: the same fingerprint the provenance lines carry, so a
    # hash seen in a run log can be checked against a state on disk.
    if len(argv) == 2 and argv[0] == "--sha":
        print(digest(payload(Path(argv[1]))))
        return 0
    try:
        if len(argv) == 3 and argv[0] == "--digest":
            return main_digest(Path(argv[1]), Path(argv[2]))
        if len(argv) != 2:
            print("usage: compose.py <script.lua> <out.lua> | --digest "
                  "<script.lua> <out> | --sha <sidecar> | --selftest")
            return 2
        script_path, out_path = Path(argv[0]), Path(argv[1])
        text, notes = compose_script(script_path)
    except ComposeError as e:
        print(f"error: {e}")
        return 1
    out_path.write_text(text)
    for n in notes:
        print(n)
    states = re.findall(r"^-- state (\S+) sha=(\S+) .* <- (.*)$", text, re.M)
    print(f"composed {out_path} ({len(states)} embedded savestate(s))")
    for name, sha, src in states:
        print(f"  {name} sha={sha} <- {src}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
