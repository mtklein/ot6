#!/usr/bin/env python3
"""fightswingslab.py -- what the driver's Fight model costs at the controls (#235).

    python3 tools/tests/fightswingslab.py model
    python3 tools/tests/fightswingslab.py write
    python3 tools/tests/fightswingslab.py run [--seeds 0,7,13,...] [--jobs N] arm
    python3 tools/tests/fightswingslab.py aggregate [arm ...]

`M.fightSwings` returned the SWING count (`1 + 2*boost` for one weapon)
where both its callers wanted the LANDED-HIT count (`1 + boost`; the
whiffing half is the empty hand -- ot6_boost.asm's own header, and the
#219 lab's histogram, `build/attempts/fight-vs-ability/lab/fight-vs-
ability/mechanic.txt`).  `fightChips` counts one chip per landed hit and
`keyBoost` picks a boost depth off `fightChips`, so the model's error is
a strategy error.  This lab asks how big a one, twice:

----------------------------------------------------------------------
`model` -- the decision table, no emulator
----------------------------------------------------------------------
Runs BOTH models through the shipped `M.keyBoost` for every (shields
standing, bank, hands) a World-of-Balance gauge can present, and prints
the cells where the chosen boost moves and the cells where the driver
claimed a break it could not land.  Plain arithmetic, so the consequence
is bounded before a single frame is emulated -- and so a claim about
"5- and 6-shield gauges" is checked rather than inherited.

----------------------------------------------------------------------
`write` / `run` / `aggregate` -- the in-play arm
----------------------------------------------------------------------
One fight: **battle 70, IFRIT and SHIVA**, both authored 6 shields
(`ot6_hud.asm`: $0109 6 OT6_PIERCE, $0108 6 OT6_SLASH) -- two of the four
bodies #235 names.  The fixture is the tracked `ifrit_entry` savestate,
"map 264 (3,7) facing IFRIT, one A-press from battle 70", and the party
it carries is four ONE-WEAPON characters (LOCKE $02 Guardian pierce,
EDGAR $0A MithrilBlade slash, SABIN $53 MetalKnuckle slash, CELES $0A
slash), which is exactly the shape the model got wrong.

The fight is played by the shipped library fighter under
`gen_ifrit_magicite.lua`'s own options, verbatim -- `tactical = false`,
`boost`, `bank = 3`, real items, `healPercent = 80`, CELES on Ice -- so
this measures the driver the route actually runs, not a lab-only policy.
`OT6_SEED_SHIFT` idles the boot point by N game-clock ticks, which is the
spread narshedescentlab.py uses; the seed each battle actually drew is
read off InitBattle's own store and printed, so seed collisions are
visible rather than assumed.

The measurement is read-only.  Four CPU exec observers, all borrowed from
the #219 lab so the two cannot count differently:

    ExecCmd@battle_code   park the acting character, its command, banked
                          and revealed BP, both hands' item ids, and the
                          target gauge
    Ot6WeaponClass        one exec per hand per swing: SWINGS ATTEMPTED
    Ot6HitJoin            one exec per landed hit per target: LANDED HITS
    SaveForMimic          the action resolved -- emit the row, with the
                          target's shields before and after

Plus a shield watch on both bodies, so "the break landed" is a gauge
reaching zero, not an inference.

An arm is just a directory name: the model under test is whatever the
working tree's `lib/ot6.lua` says.  Run `before`, apply the fix, run
`after`.  Every attempt is kept, wipes and frame-cap runs included;
nothing selects a run.
"""
