# ------------------------------------------------------------ model ------
def model_table():
    """Both models through keyBoost, for every gauge the WoB presents.

    The two models are the arithmetic, transcribed from the two versions of
    the library function; keyBoost's own rule is re-implemented here in the
    two lines it is, so the table is derivable by hand from this file.
    """
    def old(hands, b):
        return (2 + 2 * b) if hands == 2 else (1 + 2 * b)

    def new(hands, b):
        return (2 + 2 * b) if hands == 2 else (1 + b)

    def key_boost(chips_at, need, bank):
        if need <= 0 or chips_at(0) <= 0:
            return None
        for b in range(bank + 1):
            if chips_at(b) >= need:
                return b, True          # claims the break this turn
        return bank, False

    print("keyBoost's chosen depth, every (shields standing, bank, hands).")
    print("`claim` is whether the driver believed the break lands THIS turn.")
    print()
    hdr = "%-6s %-5s %-5s | %-5s %-5s | %-5s %-5s | %s" % (
        "hands", "need", "bank", "old", "claim", "new", "claim", "verdict")
    print(hdr)
    print("-" * len(hdr))
    moved = falseclaim = 0
    for hands in (1, 2):
        for need in range(1, 9):
            for bank in range(0, 4):
                o = key_boost(lambda b: old(hands, b), need, bank)
                n = key_boost(lambda b: new(hands, b), need, bank)
                if o is None and n is None:
                    continue
                ob, oc = o
                nb, nc = n
                # the ROM's own ceiling, which is what `new` models
                reachable = new(hands, bank) >= need
                notes = []
                if ob != nb:
                    notes.append("DEPTH %d->%d" % (ob, nb))
                    moved += 1
                if oc and not reachable:
                    notes.append("FALSE CLAIM (ceiling %d < %d)"
                                 % (new(hands, bank), need))
                    falseclaim += 1
                if not notes:
                    continue
                print("%-6d %-5d %-5d | %-5d %-5s | %-5d %-5s | %s" % (
                    hands, need, bank, ob, oc, nb, nc, "; ".join(notes)))
    print()
    print("cells where the chosen depth moves: %d" % moved)
    print("cells where the old model claimed a break the ROM cannot land: %d"
          % falseclaim)
    print()
    print("(two-weapon rows never appear: the pair branch was already right.)")


# ------------------------------------------------------------ write ------
def write(arm, shift, path=None):
    src = LAB_LUA.replace("@ARM@", arm).replace("@SHIFT@", str(shift))
    path = path or os.path.join(OUT, "lab-%s.lua" % arm)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(src)
    return path


# -------------------------------------------------------------- run ------
def run_one(arm, seed):
    d = os.path.join(OUT, arm)
    os.makedirs(d, exist_ok=True)
    # one lab file per seed: the arm and the shift are stamped into its own
    # [result] line, and two seeds running at once never share a path
    per = os.path.join(d, "lab-seed%02d.lua" % seed)
    write(arm, seed, per)
    log = os.path.join(d, "seed%02d.log" % seed)
    env = dict(os.environ)
    env.update({
        "OT6_RETRIES": "1", "OT6_SEED_SHIFT": str(seed),
        "OT6_NO_PUBLISH": "1",
        "OT6_TIMEOUT": env.get("OT6_TIMEOUT", "2400"),
        "OT6_ARTIFACT_DIR": os.path.join(d, "seed%02d" % seed),
        "OT6_WORKER": "fswings-%s-%02d" % (arm, seed),
    })
    os.makedirs(env["OT6_ARTIFACT_DIR"], exist_ok=True)
    with open(os.path.join(d, "seed%02d.out" % seed), "w") as out:
        rc = subprocess.run(["sh", os.path.join(ROOT, "tools/tests/run.sh"),
                             per, log],
                            cwd=ROOT, env=env, stdout=out,
                            stderr=subprocess.STDOUT).returncode
    return arm, seed, rc, summarize(log)


# -------------------------------------------------------- reading a log --
PASS = re.compile(r"^\[ot6\] PASS \(frame (\d+)\)")
FAILV = re.compile(r"^\[ot6\] FAIL: (.*)")
RESULT = re.compile(r"^\[ot6\] \[result\] (.*)")
ACT = re.compile(r"^\[ot6\] \[fs-act\] turn=(\d+) f(\d+) slot=(\d+) "
                 r"char=([0-9A-F]{2}) (\S+)\(\$[0-9A-F]{2}\) bp=(\d+) "
                 r"rev=(\d+) hands=(\d+) rh=\$([0-9A-F]{2}) lh=\$([0-9A-F]{2}) "
                 r"tgt=(\S+) sh=(-?\d+)->(-?\d+) chips=(-?\d+) "
                 r"swings=(\d+) hits=(\d+) dmg=(-?\d+) claim=(\S+)")
KEYED = re.compile(r"^\[ot6\] \[fslab\] actor=(\d+) KEYED: (.*?) lands (\d+) "
                   r"chip\(s\) on slot (\d+)'s (\d+) shield\(s\) -- (.*)")
BREAK = re.compile(r"^\[ot6\] \[fs-break\] slot=(\d+) turn=(\d+) f(\d+)")
GEAR = re.compile(r"^\[ot6\] \[fs-gear\] (.*)")


def kv(s):
    out = {}
    for p in s.split():
        if "=" in p:
            k, v = p.split("=", 1)
            out[k] = v
    return out


def summarize(log):
    r = dict(verdict="NONE", frame=None, fail="", result=None, acts=[],
             keyed=[], breaks=[], gear=[])
    if not os.path.exists(log):
        r["fail"] = "no log"
        return r
    for line in open(log, errors="replace"):
        line = line.rstrip("\n")
        m = PASS.match(line)
        if m:
            r["verdict"], r["frame"] = "PASS", int(m.group(1))
            continue
        m = FAILV.match(line)
        if m:
            r["verdict"], r["fail"] = "FAIL", m.group(1)[:200]
            continue
        m = RESULT.match(line)
        if m:
            r["result"] = kv(m.group(1))
            continue
        m = ACT.match(line)
        if m:
            g = m.groups()
            r["acts"].append(dict(
                turn=int(g[0]), f=int(g[1]), slot=int(g[2]), char=g[3],
                cmd=g[4], bp=int(g[5]), rev=int(g[6]), hands=int(g[7]),
                rh=g[8], lh=g[9], tgt=g[10], sh0=int(g[11]), sh1=int(g[12]),
                chips=int(g[13]), swings=int(g[14]), hits=int(g[15]),
                dmg=int(g[16]), claim=g[17]))
            continue
        m = KEYED.match(line)
        if m:
            r["keyed"].append(dict(actor=int(m.group(1)), what=m.group(2),
                                   chips=int(m.group(3)), slot=int(m.group(4)),
                                   need=int(m.group(5)), why=m.group(6)))
            continue
        m = BREAK.match(line)
        if m:
            r["breaks"].append((int(m.group(1)), int(m.group(2))))
            continue
        m = GEAR.match(line)
        if m:
            r["gear"].append(m.group(1))
    return r


def aggregate(arms):
    """Per arm: the per-seed result table, the Fight swing/hit ladder as this
    ROM played it, and every keyed claim with whether it came true."""
    for arm in arms:
        d = os.path.join(OUT, arm)
        logs = sorted(f for f in os.listdir(d) if f.endswith(".log")) \
            if os.path.isdir(d) else []
        print("== %s (%d log%s) ==" % (arm, len(logs),
                                       "" if len(logs) == 1 else "s"))
        if not logs:
            print("  (nothing run)\n")
            continue
        print("%-6s %-5s %-7s %8s %6s %10s %10s %s" % (
            "shift", "seed", "outcome", "frames", "turns", "ifr_break",
            "shv_break", "verdict"))
        seen = defaultdict(list)
        ladder = defaultdict(lambda: defaultdict(int))
        claims = []
        for name in logs:
            s = summarize(os.path.join(d, name))
            res = s["result"] or {}
            print("%-6s %-5s %-7s %8s %6s %10s %10s %s" % (
                res.get("shift", "?"), "$" + res.get("seed", "??"),
                res.get("outcome", "-"), res.get("t", "-"),
                res.get("turns", "-"),
                "t%s/f%s" % (res.get("ifr_break_turn", "-"),
                             res.get("ifr_break_t", "-")),
                "t%s/f%s" % (res.get("shv_break_turn", "-"),
                             res.get("shv_break_t", "-")),
                s["verdict"] + ((" " + s["fail"][:40]) if s["fail"] else "")))
            if res.get("seed"):
                seen[res["seed"]].append(res.get("shift"))
            for a in s["acts"]:
                if a["cmd"] == "Fight":
                    ladder[(a["hands"], a["rev"])][a["hits"]] += 1
                if a["claim"] != "-":
                    claims.append((name, a))
        print()
        dup = {k: v for k, v in seen.items() if len(v) > 1}
        if dup:
            print("  seed collisions (the same fight replayed): %s" % dup)
        print("  every Fight this arm played, (armed hands, revealed BP) "
              "-> landed hits:count")
        for k in sorted(ladder):
            h = ladder[k]
            print("    hands=%d bp=%d  %s" % (
                k[0], k[1], ",".join("%d:%d" % (v, h[v]) for v in sorted(h))))
        print()
        print("  every keyed claim, carried onto the action it was planned "
              "for (claim=<line>/<chips>/<shields>/breaks|best):")
        kept = missed = 0
        for name, a in claims:
            what, chips, need, kind = a["claim"].split("/")
            if kind != "breaks":
                continue                 # "the most the bank allows": no claim
            need = int(need[:-2])
            ok = a["sh1"] == 0 and a["sh0"] > 0
            # a claim is only judged against the gauge it was made about: an
            # ally acting in between can drop the gauge before this turn
            # resolves, and that is a different story from a wrong model
            if a["sh0"] != need:
                verdict = "STALE (gauge moved to %d before the turn resolved)" \
                    % a["sh0"]
            elif ok:
                verdict = "BROKE"
                kept += 1
            else:
                verdict = "DID NOT BREAK"
                missed += 1
            print("    %-11s t%-3d slot=%d %-14s claims %s chips on %d -> "
                  "%d landed hit(s), sh %d->%d  %s" % (
                      name, a["turn"], a["slot"], what.replace("_", " "),
                      chips[:-5], need, a["hits"], a["sh0"], a["sh1"],
                      verdict))
        print("    claims judged on the gauge they named -- kept: %d  "
              "BROKEN: %d" % (kept, missed))
        print()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["model", "write", "run", "aggregate"])
    ap.add_argument("arms", nargs="*")
    ap.add_argument("--seeds", default="0,7,13,19,27,34,41,53")
    ap.add_argument("--jobs", type=int, default=4)
    a = ap.parse_args()
    if a.cmd == "model":
        model_table()
        return 0
    if a.cmd == "write":
        print(write(a.arms[0] if a.arms else "arm", 0))
        return 0
    if a.cmd == "aggregate":
        arms = a.arms or [d for d in sorted(os.listdir(OUT))
                          if os.path.isdir(os.path.join(OUT, d))] \
            if os.path.isdir(OUT) else []
        aggregate(arms)
        return 0
    seeds = [int(x) for x in a.seeds.split(",") if x != ""]
    if not a.arms:
        sys.exit("run: name an arm (a directory label, e.g. before / after)")
    jobs = [(arm, s) for arm in a.arms for s in seeds]
    rcs = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=a.jobs) as ex:
        for arm, seed, rc, s in ex.map(lambda j: run_one(*j), jobs):
            res = s["result"] or {}
            print("%-8s shift=%-3d rc=%d %-5s seed=%-3s %s t=%s turns=%s "
                  "ifr=%s shv=%s %s" % (
                      arm, seed, rc, s["verdict"], res.get("seed", "??"),
                      res.get("outcome", "-"), res.get("t", "-"),
                      res.get("turns", "-"), res.get("ifr_break_turn", "-"),
                      res.get("shv_break_turn", "-"), s["fail"][:60]))
            sys.stdout.flush()
            rcs.append(rc)
    return 0


if __name__ == "__main__":
    sys.exit(main())
