-- ------------------------------------------------------------- walking --
local function map() return H.mapId() & 0x1ff end
local function bright() return emu.getState()["ppu.screenBrightness"] or 0 end
local function settled(m)
  return function()
    return map() == m and H.hasControl() and H.tileAligned() and bright() >= 15
  end
end

-- Hold a direction onto a door or exit tile until pred holds; a battle on
-- the way (the world step into Narshe can roll one) is fought, and a
-- dialog is paged.
local function pressWalk(dir, pred, maxFrames, what)
  local ph = 0
  local W = H.newWalkFighter("school: " .. what)
  return H.withReset(H.driveUntil(pred, maxFrames, {
    H.call(function()
      ph = (ph + 1) % 8
      if W.frame() then return end
      if H.dialogWaiting() then H.setPad(ph < 4 and { "a" } or {}); return end
      H.setPad({ [dir] = true })
    end),
  }, what), function() ph = 0 end)
end

-- Walk to a room's tile and step through the door above/below it.
local function door(x, y, dir, dest, what)
  return {
    H.navTo(x, y, { maxFrames = 6000, playBattles = true }),
    pressWalk(dir, function() return map() == dest end, 1200, what),
    H.waitUntil(settled(dest), 1800, what .. ": control", 5),
    H.waitFrames(20),
  }
end

-- ------------------------------------------------------- reading a box --
-- Page one advisor's dialog: every keypress wait is a page.  The window
-- has finished drawing when the field waits on a key ($ba=1, $d3=1); the
-- screenshot is taken 12 frames into the wait, then A is tapped.
local shots = {}
local function readBox(id, room)
  local seen, waitAt, pressed, ph = 0, nil, false, 0
  local done = false
  return H.withReset(H.driveUntil(function() return done end, 6000, {
    H.call(function()
      ph = (ph + 1) % 8
      if H.dialogWaiting() then
        if not waitAt then
          waitAt, pressed = H.frame, false
          seen = seen + 1
          H.assertEq(H.readWord(0x00d0) & 0x1fff, id, string.format(
            "the dialog on screen ($00D0) is $%04X (page %d)", id, seen))
        end
        local age = H.frame - waitAt
        if age == 12 then
          local tag = string.format("school_%04X_p%d", id, seen)
          H.screenshot(tag)
          shots[#shots + 1] = tag
        end
        H.setPad((age > 16 and ph < 4) and { "a" } or {})
        return
      end
      H.setPad({})
      waitAt = nil
      if seen > 0 and H.hasControl() then done = true end
    end),
  }, string.format("read dlg $%04X (%s)", id, room)), function()
    seen, waitAt, pressed, ph, done = 0, nil, false, 0, false
  end), function() return seen end
end

local function talk(obj, id, room)
  local step, seenOf = readBox(id, room)
  return {
    H.talkToObj(obj, string.format("%s advisor obj $%02X (dlg $%04X)", room, obj, id)),
    step,
    H.call(function()
      H.assertEq(seenOf(), pagesOf[id], string.format(
        "dlg $%04X waited on %d page(s), its text has %d: no page overflows",
        id, seenOf(), pagesOf[id]))
      H.log(string.format("school: dlg $%04X shown in game, %d page(s)", id, seenOf()))
    end),
    H.waitFrames(10),
  }
end

-- An advisor who asks first: the prompt ($0273, "Want to learn more about
-- Espers?" Yes/No) waits with a two-row choice up ($056F = 2, cursor
-- $056E); it is screenshotted, the cursor must rest on Yes (row 0), and
-- A takes it, which plays the lesson (event _cc36a6: choice -> $0274).
local function talkAfterYes(obj, promptId, id, room)
  local ph, waitAt, answered = 0, nil, false
  local step, seenOf = readBox(id, room)
  return {
    H.talkToObj(obj, string.format("%s advisor obj $%02X (dlg $%04X)", room, obj, promptId)),
    H.withReset(H.driveUntil(function() return answered end, 3000, {
      H.call(function()
        ph = (ph + 1) % 8
        if H.dialogWaiting() and H.readByte(0x056f) < 2 and not waitAt then
          -- the prompt's first page ("Seems you have a piece of Magicite.")
          H.setPad(ph < 4 and { "a" } or {}); return
        end
        if not (H.dialogWaiting() and H.readByte(0x056f) >= 2) then
          if waitAt then answered = true end  -- the confirm closed the prompt
          H.setPad({}); return
        end
        if not waitAt then
          waitAt = H.frame
          H.assertEq(H.readWord(0x00d0) & 0x1fff, promptId, string.format(
            "the prompt on screen ($00D0) is $%04X", promptId))
          H.assertEq(H.readByte(0x056e), 0, "the choice cursor rests on Yes")
        end
        local age = H.frame - waitAt
        if age == 12 then H.screenshot(string.format("school_%04X_prompt", promptId)) end
        -- A held from frame 17 of the wait until the window takes it
        -- (the wait ends); the pad is released when this step ends
        H.setPad(age > 16 and { "a" } or {})
      end),
    }, string.format("answer Yes to dlg $%04X", promptId)), function()
      ph, waitAt, answered = 0, nil, false
    end),
    H.waitFrames(6),
    H.release(),
    step,
    H.call(function()
      H.assertEq(seenOf(), pagesOf[id], string.format(
        "dlg $%04X waited on %d page(s), its text has %d: no page overflows",
        id, seenOf(), pagesOf[id]))
      H.log(string.format("school: dlg $%04X shown in game, %d page(s)", id, seenOf()))
    end),
    H.waitFrames(10),
  }
end

local function flat(list)
  local out = {}
  for _, s in ipairs(list) do
    if s.tick then out[#out + 1] = s
    else for _, t in ipairs(flat(s)) do out[#out + 1] = t end end
  end
  return out
end

